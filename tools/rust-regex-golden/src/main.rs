// Searches

#[derive(Clone, Debug, Eq, PartialEq)]
struct Search {
    group_count: usize,
    group_names: Vec<Option<String>>,
    is_match: bool,
    captures: Option<Groups>,
    /// Every match in iteration order, with all group spans.
    matches: Vec<Groups>,
}

fn meta_groups(captures: &regex_automata::util::captures::Captures) -> Groups {
    (0..captures.group_len())
        .map(|index| captures.get_group(index).map(|span| (span.start, span.end)))
        .collect()
}

/// The public `Regex::captures_len` definition. `meta::Regex::captures_len`
/// counts only groups that survive translation, so it omits a group elided by
/// `{0}`, such as group 1 in `(a){0}(a)`, while the group info keeps its slot.
fn group_len(regex: &meta::Regex) -> usize {
    regex.group_info().group_len(PatternID::ZERO)
}

fn meta_first(regex: &meta::Regex, input: Input<'_>) -> Option<Groups> {
    let mut captures = regex.create_captures();
    regex.captures(input, &mut captures);
    captures.is_match().then(|| meta_groups(&captures))
}

/// The group spans of either public `Captures` type.
macro_rules! public_groups {
    ($captures:expr) => {
        $captures
            .iter()
            .map(|group| group.map(|m| (m.start(), m.end())))
            .collect::<Groups>()
    };
}

/// Searches with either public regex type, whose methods share names and
/// shapes but not types.
macro_rules! public_search_with {
    ($regex:expr, $text:expr) => {{
        let (regex, text) = ($regex, $text);
        let found: Vec<(usize, usize)> = regex
            .find_iter(text)
            .map(|m| (m.start(), m.end()))
            .collect();
        let matches: Vec<Groups> = regex
            .captures_iter(text)
            .map(|captures| public_groups!(captures))
            .collect();
        check_iteration(&found, &matches)?;
        Ok(Search {
            group_count: regex.captures_len(),
            group_names: regex
                .capture_names()
                .map(|name| name.map(str::to_string))
                .collect(),
            is_match: regex.is_match(text),
            captures: regex
                .captures(text)
                .map(|captures| public_groups!(captures)),
            matches,
        })
    }};
}

fn public_search(regex: &PublicRegex, text: &[u8]) -> Result<Search, String> {
    match regex {
        PublicRegex::String(regex) => {
            let text = std::str::from_utf8(text)
                .map_err(|_| "internal error: a string search of text that is not UTF-8")?;
            public_search_with!(regex, text)
        }
        PublicRegex::Bytes(regex) => public_search_with!(regex, text),
    }
}

fn meta_search(regex: &meta::Regex, text: &[u8], window: &Range<usize>) -> Result<Search, String> {
    let input = || Input::new(text).range(window.clone());
    let found: Vec<(usize, usize)> = regex
        .find_iter(input())
        .map(|m| (m.start(), m.end()))
        .collect();
    let matches: Vec<Groups> = regex
        .captures_iter(input())
        .map(|captures| meta_groups(&captures))
        .collect();
    check_iteration(&found, &matches)?;
    Ok(Search {
        group_count: group_len(regex),
        group_names: regex
            .group_info()
            .pattern_names(PatternID::ZERO)
            .map(|name| name.map(str::to_string))
            .collect(),
        is_match: regex.is_match(input()),
        captures: meta_first(regex, input()),
        matches,
    })
}

fn check_iteration(found: &[(usize, usize)], matches: &[Groups]) -> Result<(), String> {
    let captured: Vec<Option<(usize, usize)>> = matches.iter().map(|groups| groups[0]).collect();
    let found: Vec<Option<(usize, usize)>> = found.iter().copied().map(Some).collect();
    if found != captured {
        return Err(format!(
            "find_iter {found:?} and captures_iter {captured:?} disagree"
        ));
    }
    Ok(())
}

struct Observed {
    search: Search,
    anchored: Option<Groups>,
    /// The full match, or `None` when it is undefined for this window.
    full: Option<Option<Groups>>,
}

/// Runs every recorded operation. Without a window, the public API is the
/// authority and the meta engine must reproduce it exactly, which validates
/// the meta configuration used for anchored, full, and windowed searches.
fn observe(
    compiled: &Compiled,
    text: &[u8],
    window: Option<Range<usize>>,
) -> Result<Observed, String> {
    let Compiled::Accepted {
        public,
        meta,
        full,
        reads_right_context,
    } = compiled
    else {
        return Err("internal error: observing a rejected pattern".to_string());
    };
    let range = window.clone().unwrap_or(0..text.len());
    let search = meta_search(meta, text, &range)?;
    if window.is_none() {
        let expected = public_search(public, text)?;
        if search != expected {
            return Err(format!(
                "meta search {search:?} differs from the public API {expected:?} on textHex={}",
                encode_hex(text)
            ));
        }
    }
    // Truncating at the window end keeps the left context exact. It loses the
    // right context only where the window stops short of the haystack end: for
    // assertions that read at or after their position, and, outside the bytes
    // API, for a window end inside a character, where truncation makes the end
    // a character boundary that an empty match may use.
    let bytes = matches!(public, PublicRegex::Bytes(_));
    let truncation_changes_result = range.end < text.len()
        && (*reads_right_context || (!bytes && !is_char_boundary(text, range.end)));
    let full = (!truncation_changes_result).then(|| {
        meta_first(
            full,
            Input::new(&text[..range.end])
                .range(range.clone())
                .anchored(Anchored::Yes),
        )
    });
    Ok(Observed {
        anchored: meta_first(
            meta,
            Input::new(text)
                .range(range.clone())
                .anchored(Anchored::Yes),
        ),
        full,
        search,
    })
}

/// Successive anchored matches, each starting where the previous one ended,
/// as regex-automata's own test suite runs anchored tests.
fn anchored_matches(meta: &meta::Regex, text: &[u8], range: &Range<usize>) -> Vec<Groups> {
    meta.captures_iter(
        Input::new(text)
            .range(range.clone())
            .anchored(Anchored::Yes),
    )
    .map(|captures| meta_groups(&captures))
    .collect()
}

