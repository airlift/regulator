package io.airlift.regulator.benchmark;

import io.airlift.slice.Slice;
import io.airlift.slice.Slices;
import io.airlift.regulator.TrinoLikePattern;
import io.trino.likematcher.LikeMatcher;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Param;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.Warmup;

import java.lang.classfile.ClassFile;
import java.lang.constant.ClassDesc;
import java.lang.constant.DirectMethodHandleDesc;
import java.lang.constant.DynamicConstantDesc;
import java.lang.constant.MethodHandleDesc;
import java.lang.constant.MethodTypeDesc;
import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.util.Arrays;
import java.util.List;
import java.util.Optional;
import java.util.concurrent.TimeUnit;
import java.util.function.Predicate;

import static java.lang.constant.ConstantDescs.CD_Class;
import static java.lang.constant.ConstantDescs.CD_MethodHandle;
import static java.lang.constant.ConstantDescs.CD_MethodHandles;
import static java.lang.constant.ConstantDescs.CD_MethodHandles_Lookup;
import static java.lang.constant.ConstantDescs.CD_Object;
import static java.lang.constant.ConstantDescs.CD_String;
import static java.lang.constant.ConstantDescs.CD_boolean;
import static java.lang.constant.ConstantDescs.CD_int;
import static java.lang.constant.ConstantDescs.CD_void;
import static java.lang.constant.ConstantDescs.INIT_NAME;
import static java.nio.charset.StandardCharsets.UTF_8;

/**
 * Matches one LIKE pattern against one input per scenario, with Regulator, Trino's SQL matcher,
 * and Trino's optimized matcher, and measures compilation and single use.
 * <p>
 * {@code candidateGenerated} runs the pattern's generated bytecode, bound the way a query engine
 * binds a constant pattern: a per-pattern hidden class that invokes the generated handle held as
 * a class-data constant. {@code candidate} keeps its published binding, a virtual call on the
 * pattern read from a field, so the ratio of the generated row to {@code candidate} measures the
 * change of binding as well as the generated code. Only {@code candidateGenerated} takes the
 * state that compiles the generated pattern, so the forks of the other methods load no generated
 * LIKE class, which would change how C2 compiles their {@code matches} call. The generated API is
 * resolved reflectively, so this source also runs against a Regulator build without it, where
 * only that method fails.
 */
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(3)
@Warmup(iterations = 10, time = 300, timeUnit = TimeUnit.MILLISECONDS)
@Measurement(iterations = 5, time = 300, timeUnit = TimeUnit.MILLISECONDS)
public class BenchmarkTrinoLike
{
    @State(Scope.Thread)
    public static class BenchmarkData
    {
        @Param
        Scenario scenario;

        private TrinoLikePattern candidate;
        private LikeMatcher trinoSql;
        private LikeMatcher trinoOptimized;
        private Slice sliceInput;
        private byte[] byteInput;
        private Slice slicePattern;
        private String stringPattern;

        @Setup
        public void setup()
        {
            Input input = scenario.input();
            slicePattern = Slices.utf8Slice(input.pattern());
            stringPattern = input.pattern();
            candidate = TrinoLikePattern.compile(slicePattern);
            trinoSql = LikeMatcher.compile(input.pattern(), Optional.empty(), false);
            trinoOptimized = LikeMatcher.compile(input.pattern(), Optional.empty(), true);
            byteInput = input.input();
            sliceInput = Slices.wrappedBuffer(byteInput);

            boolean candidateResult = candidate.matches(sliceInput);
            boolean sqlResult = trinoSql.match(byteInput);
            boolean optimizedResult = trinoOptimized.match(byteInput);
            if (candidateResult != input.expected() ||
                    sqlResult != input.expected() ||
                    optimizedResult != input.expected()) {
                throw new IllegalStateException("benchmark outcome mismatch for " + scenario);
            }
        }
    }

    @State(Scope.Thread)
    public static class GeneratedData
    {
        private Predicate<Slice> candidateGenerated;
        private Slice sliceInput;

        @Setup
        public void setup(BenchmarkData data)
                throws ReflectiveOperationException
        {
            candidateGenerated = generatedCaller(data.slicePattern);
            sliceInput = data.sliceInput;
            if (candidateGenerated != null && candidateGenerated.test(data.sliceInput) != data.scenario.input().expected()) {
                throw new IllegalStateException("generated benchmark outcome mismatch for " + data.scenario);
            }
        }
    }

    public enum Scenario
    {
        EXACT_MATCH,
        PREFIX_LARGE,
        SUFFIX_LARGE,
        CONTAINS_ABSENT,
        CONTAINS_LATE,
        ORDERED_LATE,
        ORDERED_DENSE_FALSE,
        ANY_ASCII,
        ANY_MULTIBYTE,
        MIXED_LATE,
        MIXED_ABSENT,
        WILDCARD_CHAIN;

        private Input input()
        {
            return switch (this) {
                case EXACT_MATCH -> benchmarkInput("needle", bytes("needle"), true);
                case PREFIX_LARGE -> benchmarkInput("needle%", inject(filled(32_768), bytes("needle"), 0), true);
                case SUFFIX_LARGE -> benchmarkInput("%needle", inject(filled(32_768), bytes("needle"), 32_762), true);
                case CONTAINS_ABSENT -> benchmarkInput("%needle%", filled(32_768), false);
                case CONTAINS_LATE -> benchmarkInput("%needle%", inject(filled(32_768), bytes("needle"), 32_700), true);
                case ORDERED_LATE -> benchmarkInput(
                        "%alpha%omega%",
                        inject(inject(filled(32_768), bytes("alpha"), 31_900), bytes("omega"), 32_700),
                        true);
                case ORDERED_DENSE_FALSE -> benchmarkInput("%aab%bba%", denseFalse(), false);
                case ANY_ASCII -> benchmarkInput("_", bytes("x"), true);
                case ANY_MULTIBYTE -> benchmarkInput("_", bytes("💰"), true);
                case MIXED_LATE -> benchmarkInput(
                        "%alpha_omega%",
                        inject(filled(32_768), bytes("alpha💰omega"), 32_700),
                        true);
                case MIXED_ABSENT -> benchmarkInput("%alpha_omega%", filled(32_768), false);
                case WILDCARD_CHAIN -> benchmarkInput(
                        "%alpha_bravo_charlie%",
                        inject(filled(1_024), bytes("alpha-bravo-charlie"), 900),
                        true);
            };
        }
    }

    private record Input(String pattern, byte[] input, boolean expected)
    {
        private Input
        {
            input = input.clone();
        }

        @Override
        public byte[] input()
        {
            return input.clone();
        }
    }

    @Benchmark
    public boolean candidate(BenchmarkData data)
    {
        return data.candidate.matches(data.sliceInput);
    }

    @Benchmark
    public boolean candidateGenerated(GeneratedData data)
    {
        Predicate<Slice> generated = data.candidateGenerated;
        if (generated == null) {
            throw new IllegalStateException("This Regulator build has no generated LIKE bytecode");
        }
        return generated.test(data.sliceInput);
    }

    @Benchmark
    public boolean trinoSql(BenchmarkData data)
    {
        return data.trinoSql.match(data.byteInput);
    }

    @Benchmark
    public boolean trinoOptimized(BenchmarkData data)
    {
        return data.trinoOptimized.match(data.byteInput);
    }

    @Benchmark
    public TrinoLikePattern candidateCompile(BenchmarkData data)
    {
        return TrinoLikePattern.compile(data.slicePattern);
    }

    @Benchmark
    public LikeMatcher trinoSqlCompile(BenchmarkData data)
    {
        return LikeMatcher.compile(data.stringPattern, Optional.empty(), false);
    }

    @Benchmark
    public boolean candidateSingleUse(BenchmarkData data)
    {
        return TrinoLikePattern.compile(data.slicePattern).matches(data.sliceInput);
    }

    @Benchmark
    public boolean trinoSqlSingleUse(BenchmarkData data)
    {
        return LikeMatcher.compile(data.stringPattern, Optional.empty(), false).match(data.byteInput);
    }

    @Benchmark
    public boolean trinoOptimizedSingleUse(BenchmarkData data)
    {
        return LikeMatcher.compile(data.stringPattern, Optional.empty(), true).match(data.byteInput);
    }

    public static void main(String[] args)
            throws ReflectiveOperationException
    {
        BenchmarkTrinoLike benchmark = new BenchmarkTrinoLike();
        int generatedComparisons = 0;
        for (Scenario scenario : Scenario.values()) {
            BenchmarkData data = new BenchmarkData();
            data.scenario = scenario;
            data.setup();
            boolean expected = scenario.input().expected();
            if (benchmark.candidateSingleUse(data) != expected ||
                    benchmark.trinoSqlSingleUse(data) != expected ||
                    benchmark.trinoOptimizedSingleUse(data) != expected ||
                    benchmark.candidateCompile(data).matches(data.sliceInput) != expected ||
                    benchmark.trinoSqlCompile(data).match(data.byteInput) != expected) {
                throw new IllegalStateException("LIKE lifecycle mismatch for " + scenario);
            }
            GeneratedData generatedData = new GeneratedData();
            generatedData.setup(data);
            if (generatedData.candidateGenerated != null) {
                if (benchmark.candidateGenerated(generatedData) != expected) {
                    throw new IllegalStateException("generated LIKE mismatch for " + scenario);
                }
                generatedComparisons++;
            }
        }
        System.out.println("Verified 60 Trino LIKE lifecycle comparisons");
        if (generatedComparisons == 0) {
            System.out.println("Skipped generated Trino LIKE comparisons: this Regulator build has no generated LIKE bytecode");
        }
        else {
            System.out.println("Verified " + generatedComparisons + " generated Trino LIKE comparisons");
        }
    }

    /**
     * Returns a caller of the generated bytecode of {@code pattern}, or {@code null} when this
     * Regulator build has no generated LIKE API. The caller is a per-pattern hidden class whose
     * {@code test} invokes the generated handle held as a class-data constant, as
     * {@code BenchmarkTrinoScanKernelDispatch} binds a constant pattern. Each match is then one
     * interface call, as {@code candidate}'s is one virtual call.
     */
    static Predicate<Slice> generatedCaller(Slice pattern)
            throws ReflectiveOperationException
    {
        Class<?> optionsType;
        try {
            optionsType = Class.forName(TrinoLikePattern.class.getName() + "$Options");
        }
        catch (ClassNotFoundException e) {
            return null;
        }
        Object options = optionsType.getMethod("defaults").invoke(null);
        optionsType.getMethod("setGenerateBytecode", boolean.class).invoke(options, true);
        TrinoLikePattern compiled = (TrinoLikePattern) TrinoLikePattern.class.getMethod("compile", Slice.class, optionsType).invoke(null, pattern, options);
        MethodHandle matches = (MethodHandle) ((Optional<?>) TrinoLikePattern.class.getMethod("generatedMatches").invoke(compiled))
                .orElseThrow(() -> new IllegalStateException("Pattern has no generated class: " + pattern.toStringUtf8()));

        ClassDesc owner = ClassDesc.of(BenchmarkTrinoLike.class.getPackageName() + ".GeneratedLikeCaller");
        ClassDesc slice = ClassDesc.of(Slice.class.getName());
        DirectMethodHandleDesc bootstrap = MethodHandleDesc.ofMethod(
                DirectMethodHandleDesc.Kind.STATIC,
                CD_MethodHandles,
                "classDataAt",
                MethodTypeDesc.of(CD_Object, CD_MethodHandles_Lookup, CD_String, CD_Class, CD_int));
        DynamicConstantDesc<?> boundMatches = DynamicConstantDesc.ofNamed(bootstrap, "_", CD_MethodHandle, 0);
        byte[] bytecode = ClassFile.of().build(owner, builder -> {
            builder.withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_FINAL);
            builder.withInterfaceSymbols(ClassDesc.of(Predicate.class.getName()));
            builder.withMethodBody(INIT_NAME, MethodTypeDesc.of(CD_void), ClassFile.ACC_PUBLIC, code ->
                    code.aload(0).invokespecial(CD_Object, INIT_NAME, MethodTypeDesc.of(CD_void)).return_());
            builder.withMethodBody("test", MethodTypeDesc.of(CD_boolean, CD_Object), ClassFile.ACC_PUBLIC, code ->
                    code.loadConstant(boundMatches).aload(1).checkcast(slice)
                            .invokevirtual(CD_MethodHandle, "invokeExact", MethodTypeDesc.of(CD_boolean, slice)).ireturn());
        });
        MethodHandles.Lookup lookup = MethodHandles.lookup().defineHiddenClassWithClassData(
                bytecode,
                List.of(matches),
                true,
                MethodHandles.Lookup.ClassOption.NESTMATE);
        @SuppressWarnings("unchecked")
        Predicate<Slice> caller = (Predicate<Slice>) lookup.lookupClass().getConstructor().newInstance();
        return caller;
    }

    private static Input benchmarkInput(String pattern, byte[] input, boolean expected)
    {
        return new Input(pattern, input, expected);
    }

    private static byte[] bytes(String value)
    {
        return value.getBytes(UTF_8);
    }

    private static byte[] filled(int length)
    {
        byte[] input = new byte[length];
        Arrays.fill(input, (byte) 'x');
        return input;
    }

    private static byte[] inject(byte[] input, byte[] value, int offset)
    {
        System.arraycopy(value, 0, input, offset, value.length);
        return input;
    }

    private static byte[] denseFalse()
    {
        byte[] input = filled(32_768);
        byte[] candidate = bytes("aabx");
        for (int offset = 0; offset + candidate.length <= input.length; offset += candidate.length) {
            System.arraycopy(candidate, 0, input, offset, candidate.length);
        }
        return input;
    }
}
