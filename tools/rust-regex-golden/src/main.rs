//! Generates golden fixtures for Regulator's Rust regex front end from the
//! pinned `regex` crate.
//!
//! Every mode reads its cases, drives the pinned crate, checks that the
//! independent routes into the crate agree, and only then writes JSONL to
//! standard output. Any disagreement aborts generation, so a fixture never
//! records a result that depends on how the generator happened to call the
//! crate.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;
use std::io::{self, BufRead, Write};
use std::ops::Range;
use std::path::Path;
use std::process::ExitCode;

use regex_automata::util::syntax as automata_syntax;
use regex_automata::{meta, Anchored, Input, MatchKind, PatternID};
use regex_syntax::ast::parse::ParserBuilder;
use regex_syntax::hir::translate::TranslatorBuilder;
use regex_syntax::hir::{Hir, Look};
use regex_test::{CompiledRegex, RegexTest, RegexTests, TestResult, TestRunner};

// `regex` 1.13.1 `Builder::default` meta configuration.
const NFA_SIZE_LIMIT: usize = 10 * (1 << 20);
const HYBRID_CACHE_CAPACITY: usize = 2 * (1 << 20);

// regex-automata `util::syntax::Config::new` defaults, which `regex` leaves
// unchanged unless a caller sets them. A case's options may set another nest
// limit; the front end exposes no other line terminator.
const DEFAULT_NEST_LIMIT: u32 = 250;
const LINE_TERMINATOR: u8 = b'\n';

/// Bound on the matches recorded per case. The true count is always recorded.
const MAX_RECORDED_MATCHES: usize = 64;

/// Upstream test file written for regex-lite. The regex crate's own suite does
/// not load it, and several of its expectations are regex-lite's ASCII-only
/// semantics rather than regex's.
const REGEX_LITE_GROUP: &str = "regex-lite";

const HEADER: &str =
    "# Generated by tools/rust-regex-golden/generate.sh from the pinned regex crate. Do not edit.";

type Groups = Vec<Option<(usize, usize)>>;

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("rust-regex-golden: {message}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let mut mode = None;
    let mut testdata = None;
    for argument in std::env::args().skip(1) {
        if let Some(value) = argument.strip_prefix("--mode=") {
            mode = Some(value.to_string());
        } else if let Some(value) = argument.strip_prefix("--testdata=") {
            testdata = Some(value.to_string());
        } else {
            return Err(format!("unknown argument {argument:?}"));
        }
    }

    let lines = match mode.as_deref() {
        Some("syntax") => syntax_mode(&read_cases(3)?)?,
        Some("match") => match_mode(&read_cases(6)?)?,
        Some("upstream") => {
            let testdata = testdata.ok_or("--mode=upstream requires --testdata=DIR")?;
            upstream_mode(Path::new(&testdata), false)?
        }
        Some("upstream-bytes") => {
            let testdata = testdata.ok_or("--mode=upstream-bytes requires --testdata=DIR")?;
            upstream_mode(Path::new(&testdata), true)?
        }
        _ => {
            return Err(
                "usage: rust-regex-golden --mode=syntax|match|upstream|upstream-bytes [--testdata=DIR]"
                    .to_string(),
            )
        }
    };

    let mut output = io::BufWriter::new(io::stdout().lock());
    for line in lines {
        writeln!(output, "{line}").map_err(|e| format!("failed to write output: {e}"))?;
    }
    output
        .flush()
        .map_err(|e| format!("failed to write output: {e}"))
}

