package io.airlift.regulator;

import org.junit.jupiter.api.Test;

import java.lang.classfile.ClassFile;
import java.lang.classfile.ClassModel;
import java.lang.classfile.constantpool.ClassEntry;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;

public class TestOptionalTrinoScanKernel
{
    /**
     * Regexp, RE2, Java, and LIKE patterns compiled without generated bytecode run representative
     * operations without loading the generated-code subclasses, the generators, the helper copies, or the
     * classfile library.
     */
    @Test
    public void testDisabledGenerationLoadsNoGeneratedCode()
            throws Exception
    {
        Path classLoadLog = Files.createTempFile("trino-scan-kernel-class-load-", ".log");
        try {
            runProbe(List.of("-Xlog:class+load=info:file=" + classLoadLog));
            assertThat(Files.readString(classLoadLog))
                    .contains("io.airlift.regulator.TrinoScanPlan source:")
                    .contains("io.airlift.regulator.VectorTrinoScanner source:")
                    .contains("io.airlift.regulator.TrinoLikePattern source:")
                    .contains("io.airlift.regulator.TrinoLikeWildcardMatcher source:")
                    .doesNotContain("io.airlift.regulator.TrinoRegexp$CompiledScanTrinoRegexp ")
                    .doesNotContain("io.airlift.regulator.TrinoRegexpMatcher$CompiledScanMatcher ")
                    .doesNotContain("io.airlift.regulator.Re2$CompiledScanRe2 ")
                    .doesNotContain("io.airlift.regulator.TrinoScanKernelGenerator")
                    .doesNotContain("io.airlift.regulator.TrinoScanKernelSupport ")
                    .doesNotContain("io.airlift.regulator.VectorTrinoScanKernelSupport ")
                    .doesNotContain("CompiledTrinoScan")
                    .doesNotContain("CompiledRe2Scan")
                    .doesNotContain("io.airlift.regulator.TrinoLikeKernelGenerator")
                    .doesNotContain("io.airlift.regulator.TrinoLikeKernelSupport ")
                    .doesNotContain("CompiledTrinoLike")
                    .doesNotContain("io.airlift.classfile.");
        }
        finally {
            Files.deleteIfExists(classLoadLog);
        }
    }

    /**
     * The dump directory property writes each generated scan class, here the RE2 executor class
     * of each attempt kind, before it is defined.
     */
    @Test
    public void testDumpDirectoryReceivesGeneratedClasses()
            throws Exception
    {
        Path directory = Files.createTempDirectory("trino-scan-kernel-dump-");
        try {
            runProbe(List.of("-Dio.airlift.regulator.scan-kernel.dump-directory=" + directory), "generate");
            try (Stream<Path> files = Files.list(directory)) {
                List<Path> classFiles = files.toList();
                assertThat(classFiles.stream().map(file -> file.getFileName().toString().replaceAll("-[0-9a-f]{8}\\.class$", "")))
                        .containsExactlyInAnyOrder("EndAnchoredCompiledRe2Scan", "PartialCompiledRe2Scan", "UnanchoredCompiledRe2Scan");
                // Each file holds a whole class of the RE2 executor interface.
                for (Path file : classFiles) {
                    ClassModel model = ClassFile.of().parse(Files.readAllBytes(file));
                    assertThat(model.interfaces().stream().map(ClassEntry::asInternalName).toList()).as(file.toString()).containsExactly("io/airlift/regulator/CompiledRe2Scan");
                }
            }
        }
        finally {
            try (Stream<Path> files = Files.list(directory)) {
                for (Path file : files.toList()) {
                    Files.delete(file);
                }
            }
            Files.delete(directory);
        }
    }

    private static void runProbe(List<String> options, String... arguments)
            throws Exception
    {
        List<String> command = new ArrayList<>();
        command.add(System.getProperty("java.home") + "/bin/java");
        command.addAll(options);
        command.add("--add-modules");
        command.add("jdk.incubator.vector");
        command.add("-cp");
        command.add(System.getProperty("java.class.path"));
        command.add(TrinoScanKernelProbe.class.getName());
        command.addAll(List.of(arguments));

        ProcessBuilder processBuilder = new ProcessBuilder(command).redirectErrorStream(true);
        processBuilder.environment().remove("JDK_JAVA_OPTIONS");
        Process process = processBuilder.start();
        String output = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        int exitCode = process.waitFor();
        assertThat(exitCode).as(output).isZero();
        assertThat(output).contains("OK");
    }
}
