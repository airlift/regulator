package io.airlift.regulator;

import io.airlift.slice.Slice;

import java.util.Collections;
import java.util.List;
import java.util.function.BiFunction;

import static io.airlift.slice.Slices.utf8Slice;

public final class ScanKernelProbe
{
    // RE2 patterns that generate a class with the option: end-anchored, partial with a retry
    // stack, and unanchored.
    private static final List<String> RE2_EXPRESSIONS = List.of("^https?://(?:www\\.)?([^/]+)/.*$", "^(a)?(b)?abcd([^/]+)/", "[?&]([^=]+)=");
    private static final List<Slice> REQUEST_INPUTS = List.of(utf8Slice("x/xéb/https://höst/path"), utf8Slice("https://höst/x"), utf8Slice("ftp://a/"));

    private ScanKernelProbe() {}

    /// Runs representative operations of patterns compiled without generated bytecode; given
    /// `generate`, compiles an RE2 pattern for the RE2 executor class of each attempt kind; or,
    /// given `request-generation` and `true` or `false`, compiles a pattern of each language with
    /// generated bytecode requested, checks whether each generates a class, and checks that its
    /// results equal those it gives without the request.
    public static void main(String[] arguments)
    {
        if (arguments.length == 2 && arguments[0].equals("request-generation")) {
            requestGeneration(Boolean.parseBoolean(arguments[1]));
            System.out.println("OK");
            return;
        }
        if (List.of(arguments).contains("generate")) {
            for (String expression : RE2_EXPRESSIONS) {
                Re2 pattern = Re2.compile(utf8Slice(expression), Re2.Options.defaults().setGenerateBytecode(true));
                check(pattern.usesGeneratedBytecode(), expression + ": no generated bytecode");
            }
            System.out.println("OK");
            return;
        }
        // Patterns that generate a class with the option: anchored, partial, unanchored, a retry
        // stack, and one whose contains keeps a literal kernel.
        for (String expression : List.of(
                "^https?://(?:www\\.)?([^/]+)/.*$",
                "^https?://([^/]+)/",
                "[?&]([^=]+)=",
                "^((a)?(b)?(c)?(d)?)abcd([^/]+)/$",
                "^(a)")) {
            TrinoRegexp regexp = TrinoRegexp.compile(utf8Slice(expression));
            check(regexp.getClass() == TrinoRegexp.class && regexp.re2().usesScanPlanForDiagnostics(), expression + ": no scan plan");
            check(!regexp.usesGeneratedBytecode(), expression + ": generated bytecode");
            for (Slice source : List.of(utf8Slice("https://www.example.com/a?b=c&d=e"), utf8Slice("abcdabcdx/"), utf8Slice("a"))) {
                regexp.contains(source);
                regexp.count(source);
                regexp.position(source, 1, 1);
                regexp.extract(source, 0);
                regexp.extract(source, 1);
                regexp.extractAll(source, 1);
                regexp.split(source);
                regexp.replace(source, utf8Slice("<$1>"));
                regexp.replace(source, _ -> utf8Slice("x"));
                TrinoRegexpMatcher matcher = regexp.matcher(source);
                while (matcher.find()) {
                    matcher.group(1);
                }
            }
        }
        // RE2 patterns compiled without the option and with it disabled.
        for (String expression : RE2_EXPRESSIONS) {
            for (Re2 pattern : List.of(Re2.compile(utf8Slice(expression)), Re2.compile(utf8Slice(expression), Re2.Options.defaults().setGenerateBytecode(false)))) {
                check(pattern.usesScanPlanForDiagnostics(), expression + ": no scan plan");
                check(!pattern.usesGeneratedBytecode(), expression + ": generated bytecode");
                for (Slice source : List.of(utf8Slice("https://www.example.com/a?b=c&d=e"), utf8Slice("abcdabcdx/"), utf8Slice("a"))) {
                    pattern.find(source);
                    pattern.find(source, 1, source.length());
                    pattern.findResult(source);
                    pattern.count(source);
                    pattern.replaceAll(source, utf8Slice("<\\1>"));
                    RegexpMatcher matcher = pattern.matcher(source);
                    while (matcher.find()) {
                        matcher.group(1);
                    }
                }
            }
        }
        // Java patterns of the same plans, and one ending in Java's $, which ends before the final
        // terminator of the last source, compiled without the option and with it disabled.
        for (String expression : List.of("(?d)^https?://(?:www\\.)?([^/]+)/.*\\z", "^(a)?(b)?abcd([^/]+)/", "[?&]([^=]+)=", "^x([a-z]+)$")) {
            for (JavaRegexp regexp : List.of(JavaRegexp.compile(utf8Slice(expression)), JavaRegexp.compile(utf8Slice(expression), JavaRegexp.Options.defaults().setGenerateBytecode(false)))) {
                check(regexp.re2().usesScanPlanForDiagnostics(), expression + ": no scan plan");
                check(!regexp.usesGeneratedBytecode(), expression + ": generated bytecode");
                check(!expression.endsWith("$") || regexp.find(utf8Slice("xab\r\n")), expression + ": no match");
                for (Slice source : List.of(utf8Slice("https://www.example.com/a?b=c&d=e"), utf8Slice("abcdabcdx/"), utf8Slice("a"), utf8Slice("xab\r\n"))) {
                    regexp.find(source);
                    regexp.find(source, 1, source.length());
                    regexp.findResult(source);
                    regexp.matchesResult(source);
                    regexp.count(source);
                    RegexpMatcher matcher = regexp.matcher(source);
                    while (matcher.find()) {
                        matcher.group(1);
                    }
                }
            }
        }
        // Rust patterns of the RE2 plans, compiled without the option and with it disabled.
        for (String expression : RE2_EXPRESSIONS) {
            for (RustRegexp regexp : List.of(RustRegexp.compile(utf8Slice(expression)), RustRegexp.compile(utf8Slice(expression), RustRegexp.Options.defaults().setGenerateBytecode(false)))) {
                check(regexp.re2().usesScanPlanForDiagnostics(), expression + ": no scan plan");
                check(!regexp.usesGeneratedBytecode(), expression + ": generated bytecode");
                for (Slice source : List.of(utf8Slice("https://www.example.com/a?b=c&d=e"), utf8Slice("abcdabcdx/"), utf8Slice("a"))) {
                    regexp.find(source);
                    regexp.find(source, 1, source.length());
                    regexp.findResult(source);
                    regexp.matchesResult(source);
                    regexp.count(source);
                    RegexpMatcher matcher = regexp.matcher(source);
                    while (matcher.find()) {
                        matcher.group(1);
                    }
                }
            }
        }
        // LIKE patterns of every plan, compiled without the option and with it disabled.
        for (String pattern : List.of("", "abc", "abc%", "%abc", "%abc%", "a%b", "%alpha_omega%", "%a%_b%")) {
            for (TrinoLikePattern like : List.of(
                    TrinoLikePattern.compile(utf8Slice(pattern)),
                    TrinoLikePattern.compile(utf8Slice(pattern), TrinoLikePattern.Options.defaults()),
                    TrinoLikePattern.compile(utf8Slice(pattern), TrinoLikePattern.Options.defaults().setEscape('\\').setGenerateBytecode(false)))) {
                check(!like.usesGeneratedBytecode() && like.generatedMatches().isEmpty(), pattern + ": generated bytecode");
                for (Slice source : List.of(utf8Slice(""), utf8Slice("abc"), utf8Slice("xalpha-omegax"), utf8Slice("xaxxbx"))) {
                    like.matches(source);
                }
            }
        }
        System.out.println("OK");
    }

    /// Compiles a pattern of each language that generates a class on the ordinary classpath, with
    /// generated bytecode requested, and checks that each generates one exactly when
    /// `expectGenerated`, with the results on a few inputs of the pattern compiled without the
    /// request.
    private static void requestGeneration(boolean expectGenerated)
    {
        Slice unanchored = utf8Slice("x([^/]+)/");
        Slice anchored = utf8Slice("^https?://([^/]+)");
        Slice contains = utf8Slice("%höst%");
        Re2 re2 = Re2.compile(unanchored, Re2.Options.defaults().setGenerateBytecode(true));
        checkSameResults("RE2", re2, Re2.compile(unanchored), (pattern, source) -> pattern.count(source) + " " + describe(pattern.findResult(source)));
        JavaRegexp java = JavaRegexp.compile(anchored, JavaRegexp.Options.defaults().setGenerateBytecode(true));
        checkSameResults("Java", java, JavaRegexp.compile(anchored), (regexp, source) -> regexp.count(source) + " " + describe(regexp.findResult(source)));
        RustRegexp rust = RustRegexp.compile(unanchored, RustRegexp.Options.defaults().setGenerateBytecode(true));
        checkSameResults("Rust", rust, RustRegexp.compile(unanchored), (regexp, source) -> regexp.count(source) + " " + describe(regexp.findResult(source)));
        TrinoRegexp trino = TrinoRegexp.compile(anchored, TrinoRegexp.Options.defaults().setGenerateBytecode(true));
        checkSameResults("Trino regexp", trino, TrinoRegexp.compile(anchored), (regexp, source) ->
                regexp.contains(source) + " " + regexp.count(source) + " " + regexp.extract(source, 1));
        TrinoLikePattern like = TrinoLikePattern.compile(contains, TrinoLikePattern.Options.defaults().setGenerateBytecode(true));
        checkSameResults("Trino LIKE", like, TrinoLikePattern.compile(contains), (pattern, source) -> String.valueOf(pattern.matches(source)));
        List<Boolean> generated = List.of(
                re2.usesGeneratedBytecode(),
                java.usesGeneratedBytecode(),
                rust.usesGeneratedBytecode(),
                trino.usesGeneratedBytecode(),
                like.usesGeneratedBytecode());
        check(generated.equals(Collections.nCopies(generated.size(), expectGenerated)), "RE2, Java, Rust, Trino regexp, and LIKE generated bytecode: " + generated);
    }

    private static <P> void checkSameResults(String language, P requested, P ordinary, BiFunction<P, Slice, String> results)
    {
        for (Slice input : REQUEST_INPUTS) {
            String expected = results.apply(ordinary, input);
            String actual = results.apply(requested, input);
            check(actual.equals(expected), "%s on [%s]: expected <%s> but was <%s>".formatted(language, input.toStringUtf8(), expected, actual));
        }
    }

    private static String describe(MatchResult result)
    {
        return result == null ? "none" : result.start() + ":" + result.end() + " " + result.groupUtf8(1);
    }

    private static void check(boolean condition, String message)
    {
        if (!condition) {
            throw new AssertionError(message);
        }
    }
}
