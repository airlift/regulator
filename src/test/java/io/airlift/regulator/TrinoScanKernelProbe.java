package io.airlift.regulator;

import io.airlift.slice.Slice;

import java.util.List;

import static io.airlift.slice.Slices.utf8Slice;

public final class TrinoScanKernelProbe
{
    private TrinoScanKernelProbe() {}

    public static void main(String[] arguments)
    {
        // Patterns that generate a class with the option: anchored, partial, unanchored, a retry
        // stack, and one whose contains keeps a literal kernel.
        for (String expression : List.of(
                "^https?://(?:www\\.)?([^/]+)/.*$",
                "^https?://([^/]+)/",
                "[?&]([^=]+)=",
                "^((a)?(b)?(c)?(d)?)abcd([^/]+)/$",
                "^(a)")) {
            TrinoRegexp regexp = TrinoRegexp.compile(utf8Slice(expression));
            check(regexp.getClass() == TrinoRegexp.class && regexp.pattern().usesTrinoScanPlanForDiagnostics(), expression + ": no scan plan");
            check(!regexp.usesGeneratedBytecode(), expression + ": generated bytecode");
            for (Slice source : List.of(utf8Slice("https://www.example.com/a?b=c&d=e"), utf8Slice("abcdabcdx/"), utf8Slice("a"))) {
                regexp.contains(source);
                regexp.count(source);
                regexp.position(source, 1, 1);
                regexp.extract(source, 0);
                regexp.extract(source, 1);
                regexp.extractAll(source, 1);
                regexp.split(source);
                regexp.replace(source, utf8Slice("<$1>"));
                regexp.replace(source, _ -> utf8Slice("x"));
                TrinoRegexpMatcher matcher = regexp.matcher(source);
                while (matcher.find()) {
                    matcher.group(1);
                }
            }
        }
        // LIKE patterns of every plan, compiled without the option and with it disabled.
        for (String pattern : List.of("", "abc", "abc%", "%abc", "%abc%", "a%b", "%alpha_omega%", "%a%_b%")) {
            for (TrinoLikePattern like : List.of(
                    TrinoLikePattern.compile(utf8Slice(pattern)),
                    TrinoLikePattern.compile(utf8Slice(pattern), TrinoLikePattern.Options.defaults()),
                    TrinoLikePattern.compile(utf8Slice(pattern), '\\', TrinoLikePattern.Options.defaults().setGenerateBytecode(false)))) {
                check(!like.usesGeneratedBytecode() && like.generatedMatches().isEmpty(), pattern + ": generated bytecode");
                for (Slice source : List.of(utf8Slice(""), utf8Slice("abc"), utf8Slice("xalpha-omegax"), utf8Slice("xaxxbx"))) {
                    like.matches(source);
                }
            }
        }
        System.out.println("OK");
    }

    private static void check(boolean condition, String message)
    {
        if (!condition) {
            throw new AssertionError(message);
        }
    }
}
