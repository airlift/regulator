package io.airlift.regulator;

import io.airlift.slice.Slice;

import java.util.List;

import static io.airlift.slice.Slices.utf8Slice;

public final class TrinoScanKernelProbe
{
    // RE2 patterns that generate a class with the option: end-anchored, partial with a retry
    // stack, and unanchored.
    private static final List<String> RE2_EXPRESSIONS = List.of("^https?://(?:www\\.)?([^/]+)/.*$", "^(a)?(b)?abcd([^/]+)/", "[?&]([^=]+)=");

    private TrinoScanKernelProbe() {}

    /**
     * Runs representative operations of patterns compiled without generated bytecode, or, given
     * {@code generate}, compiles an RE2 pattern for the RE2 executor class of each attempt kind.
     */
    public static void main(String[] arguments)
    {
        if (List.of(arguments).contains("generate")) {
            for (String expression : RE2_EXPRESSIONS) {
                Re2 pattern = Re2.compile(utf8Slice(expression), Re2.Options.defaults().setGenerateBytecode(true));
                check(pattern.usesGeneratedBytecode(), expression + ": no generated bytecode");
            }
            System.out.println("OK");
            return;
        }
        // Patterns that generate a class with the option: anchored, partial, unanchored, a retry
        // stack, and one whose contains keeps a literal kernel.
        for (String expression : List.of(
                "^https?://(?:www\\.)?([^/]+)/.*$",
                "^https?://([^/]+)/",
                "[?&]([^=]+)=",
                "^((a)?(b)?(c)?(d)?)abcd([^/]+)/$",
                "^(a)")) {
            TrinoRegexp regexp = TrinoRegexp.compile(utf8Slice(expression));
            check(regexp.getClass() == TrinoRegexp.class && regexp.pattern().usesTrinoScanPlanForDiagnostics(), expression + ": no scan plan");
            check(!regexp.usesGeneratedBytecode(), expression + ": generated bytecode");
            for (Slice source : List.of(utf8Slice("https://www.example.com/a?b=c&d=e"), utf8Slice("abcdabcdx/"), utf8Slice("a"))) {
                regexp.contains(source);
                regexp.count(source);
                regexp.position(source, 1, 1);
                regexp.extract(source, 0);
                regexp.extract(source, 1);
                regexp.extractAll(source, 1);
                regexp.split(source);
                regexp.replace(source, utf8Slice("<$1>"));
                regexp.replace(source, _ -> utf8Slice("x"));
                TrinoRegexpMatcher matcher = regexp.matcher(source);
                while (matcher.find()) {
                    matcher.group(1);
                }
            }
        }
        // RE2 patterns compiled without the option and with it disabled.
        for (String expression : RE2_EXPRESSIONS) {
            for (Re2 pattern : List.of(Re2.compile(utf8Slice(expression)), Re2.compile(utf8Slice(expression), Re2.Options.defaults().setGenerateBytecode(false)))) {
                check(pattern.usesTrinoScanPlanForDiagnostics(), expression + ": no scan plan");
                check(!pattern.usesGeneratedBytecode(), expression + ": generated bytecode");
                for (Slice source : List.of(utf8Slice("https://www.example.com/a?b=c&d=e"), utf8Slice("abcdabcdx/"), utf8Slice("a"))) {
                    pattern.find(source);
                    pattern.find(source, 1, source.length());
                    pattern.findResult(source);
                    pattern.count(source);
                    pattern.replaceAll(source, utf8Slice("<\\1>"));
                    Re2Matcher matcher = pattern.matcher(source);
                    while (matcher.find()) {
                        matcher.group(1);
                    }
                }
            }
        }
        // Java patterns of the same plans, and one ending in Java's $, which ends before the final
        // terminator of the last source, compiled without the option and with it disabled.
        for (String expression : List.of("(?d)^https?://(?:www\\.)?([^/]+)/.*\\z", "^(a)?(b)?abcd([^/]+)/", "[?&]([^=]+)=", "^x([a-z]+)$")) {
            for (JavaRegexp regexp : List.of(JavaRegexp.compile(utf8Slice(expression)), JavaRegexp.compile(utf8Slice(expression), JavaRegexp.Options.defaults().setGenerateBytecode(false)))) {
                check(regexp.pattern().usesTrinoScanPlanForDiagnostics(), expression + ": no scan plan");
                check(!regexp.usesGeneratedBytecode(), expression + ": generated bytecode");
                check(!expression.endsWith("$") || regexp.find(utf8Slice("xab\r\n")), expression + ": no match");
                for (Slice source : List.of(utf8Slice("https://www.example.com/a?b=c&d=e"), utf8Slice("abcdabcdx/"), utf8Slice("a"), utf8Slice("xab\r\n"))) {
                    regexp.find(source);
                    regexp.find(source, 1, source.length());
                    regexp.findResult(source);
                    regexp.matchesResult(source);
                    regexp.count(source);
                    Re2Matcher matcher = regexp.matcher(source);
                    while (matcher.find()) {
                        matcher.group(1);
                    }
                }
            }
        }
        // LIKE patterns of every plan, compiled without the option and with it disabled.
        for (String pattern : List.of("", "abc", "abc%", "%abc", "%abc%", "a%b", "%alpha_omega%", "%a%_b%")) {
            for (TrinoLikePattern like : List.of(
                    TrinoLikePattern.compile(utf8Slice(pattern)),
                    TrinoLikePattern.compile(utf8Slice(pattern), TrinoLikePattern.Options.defaults()),
                    TrinoLikePattern.compile(utf8Slice(pattern), '\\', TrinoLikePattern.Options.defaults().setGenerateBytecode(false)))) {
                check(!like.usesGeneratedBytecode() && like.generatedMatches().isEmpty(), pattern + ": generated bytecode");
                for (Slice source : List.of(utf8Slice(""), utf8Slice("abc"), utf8Slice("xalpha-omegax"), utf8Slice("xaxxbx"))) {
                    like.matches(source);
                }
            }
        }
        System.out.println("OK");
    }

    private static void check(boolean condition, String message)
    {
        if (!condition) {
            throw new AssertionError(message);
        }
    }
}
