package io.airlift.regulator;

import io.airlift.slice.Slice;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Param;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.Warmup;

import java.io.IOException;
import java.lang.classfile.ClassFile;
import java.lang.constant.ClassDesc;
import java.lang.constant.DirectMethodHandleDesc;
import java.lang.constant.DynamicConstantDesc;
import java.lang.constant.MethodHandleDesc;
import java.lang.constant.MethodTypeDesc;
import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;
import java.util.List;
import java.util.concurrent.TimeUnit;
import java.util.function.Predicate;

import static io.airlift.regulator.TestingTrinoRowsBenchmarkInputs.MISSING_CORPUS_DIRECTORY;
import static java.lang.constant.ConstantDescs.CD_Class;
import static java.lang.constant.ConstantDescs.CD_MethodHandle;
import static java.lang.constant.ConstantDescs.CD_MethodHandles;
import static java.lang.constant.ConstantDescs.CD_MethodHandles_Lookup;
import static java.lang.constant.ConstantDescs.CD_Object;
import static java.lang.constant.ConstantDescs.CD_String;
import static java.lang.constant.ConstantDescs.CD_boolean;
import static java.lang.constant.ConstantDescs.CD_int;
import static java.lang.constant.ConstantDescs.CD_void;
import static java.lang.constant.ConstantDescs.INIT_NAME;

/**
 * Normative Trino LIKE rows: the cells of {@link BenchmarkTrinoRows}, with each literal searched by
 * the LIKE pattern {@code %literal%}, and each ordered pair by {@code %a%b%}, matched once per row as
 * Trino calls LIKE. {@code matches} runs the interpreted pattern and {@code matchesGenerated} its
 * generated bytecode, each bound the way a query engine binds a constant pattern: a per-pattern
 * hidden class that invokes the {@code (Slice)boolean} handle held as a class-data constant. Only
 * {@code matchesGenerated} takes the state that compiles the generated pattern, so the forks of
 * {@code matches} load no generated LIKE class, which would change how C2 compiles the interpreted
 * call. Setup verifies the sampled rows' checksum and each cell's hit rows.
 */
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(5)
@Warmup(iterations = 4, time = 400, timeUnit = TimeUnit.MILLISECONDS)
@Measurement(iterations = 4, time = 400, timeUnit = TimeUnit.MILLISECONDS)
public class BenchmarkTrinoLikeRows
{
    @State(Scope.Thread)
    public static class BenchmarkData
    {
        @Param({"english", "russian", "chinese", "nginx", "apache", "loghub", "gharchive"})
        String workload;

        @Param({
                "low-none",
                "low-selective",
                "low-common",
                "mid-none",
                "mid-selective",
                "mid-common",
                "high-none",
                "high-selective",
                "high-common",
                "ordered-none",
                "ordered-selective",
                "ordered-common",
                "picked-1",
                "picked-2",
        })
        String literal;

        @Param(MISSING_CORPUS_DIRECTORY)
        String corpusDirectory;

        private TestingTrinoRowsBenchmarkInputs.Input input;
        private Predicate<Slice> matches;
        private Slice[] sources;
        private int sourceIndex;

        @Setup
        public void setup()
                throws IOException, ReflectiveOperationException
        {
            input = TestingTrinoRowsBenchmarkInputs.create(workload, literal, corpusDirectory);
            TrinoLikePattern pattern = TrinoLikePattern.compile(input.likePattern(), TrinoLikePattern.Options.defaults());
            matches = constantCaller(MethodHandles.lookup()
                    .findVirtual(TrinoLikePattern.class, "matches", MethodType.methodType(boolean.class, Slice.class))
                    .bindTo(pattern));
            input.verifyHitRows(matches);
            sources = input.sources().toArray(Slice[]::new);
            sourceIndex = 0;
        }

        public void setWorkload(String workload)
        {
            this.workload = workload;
        }

        public void setLiteral(String literal)
        {
            this.literal = literal;
        }

        public void setCorpusDirectory(String corpusDirectory)
        {
            this.corpusDirectory = corpusDirectory;
        }

        public void setSourceIndex(int sourceIndex)
        {
            this.sourceIndex = sourceIndex;
        }

        private Slice nextSource()
        {
            Slice source = sources[sourceIndex];
            sourceIndex = (sourceIndex + 1) & (sources.length - 1);
            return source;
        }
    }

    @State(Scope.Thread)
    public static class GeneratedData
    {
        private Predicate<Slice> matches;

        @Setup
        public void setup(BenchmarkData data)
                throws ReflectiveOperationException
        {
            TrinoLikePattern pattern = TrinoLikePattern.compile(data.input.likePattern(), TrinoLikePattern.Options.defaults().setGenerateBytecode(true));
            matches = constantCaller(pattern.generatedMatches()
                    .orElseThrow(() -> new IllegalStateException("Pattern has no generated class: " + data.input.likePattern().toStringUtf8())));
            data.input.verifyHitRows(matches);
        }
    }

    @Benchmark
    public boolean matches(BenchmarkData data)
    {
        return data.matches.test(data.nextSource());
    }

    @Benchmark
    public boolean matchesGenerated(BenchmarkData data, GeneratedData generated)
    {
        return generated.matches.test(data.nextSource());
    }

    /**
     * Returns an instance of a per-pattern hidden class whose {@code test} invokes {@code matches},
     * a {@code (Slice)boolean} handle, held as a class-data constant, as
     * {@code BenchmarkTrinoLikeTpch} binds a constant pattern. Each row is then one interface call
     * to a constant target.
     */
    private static Predicate<Slice> constantCaller(MethodHandle matches)
            throws ReflectiveOperationException
    {
        ClassDesc owner = ClassDesc.of(BenchmarkTrinoLikeRows.class.getPackageName() + ".ConstantLikeRowsCaller");
        ClassDesc slice = ClassDesc.of(Slice.class.getName());
        DirectMethodHandleDesc bootstrap = MethodHandleDesc.ofMethod(
                DirectMethodHandleDesc.Kind.STATIC,
                CD_MethodHandles,
                "classDataAt",
                MethodTypeDesc.of(CD_Object, CD_MethodHandles_Lookup, CD_String, CD_Class, CD_int));
        DynamicConstantDesc<?> boundMatches = DynamicConstantDesc.ofNamed(bootstrap, "_", CD_MethodHandle, 0);
        byte[] bytecode = ClassFile.of().build(owner, builder -> {
            builder.withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_FINAL);
            builder.withInterfaceSymbols(ClassDesc.of(Predicate.class.getName()));
            builder.withMethodBody(INIT_NAME, MethodTypeDesc.of(CD_void), ClassFile.ACC_PUBLIC, code ->
                    code.aload(0).invokespecial(CD_Object, INIT_NAME, MethodTypeDesc.of(CD_void)).return_());
            builder.withMethodBody("test", MethodTypeDesc.of(CD_boolean, CD_Object), ClassFile.ACC_PUBLIC, code ->
                    code.loadConstant(boundMatches).aload(1).checkcast(slice)
                            .invokevirtual(CD_MethodHandle, "invokeExact", MethodTypeDesc.of(CD_boolean, slice)).ireturn());
        });
        MethodHandles.Lookup lookup = MethodHandles.lookup().defineHiddenClassWithClassData(
                bytecode,
                List.of(matches),
                true,
                MethodHandles.Lookup.ClassOption.NESTMATE);
        @SuppressWarnings("unchecked")
        Predicate<Slice> caller = (Predicate<Slice>) lookup.lookupClass().getConstructor().newInstance();
        return caller;
    }
}
