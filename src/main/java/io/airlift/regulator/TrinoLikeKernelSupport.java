package io.airlift.regulator;

import java.lang.invoke.MethodHandles;
import java.lang.invoke.VarHandle;
import java.nio.ByteOrder;

/// The helpers that classes generated by [TrinoLikeKernelGenerator] call.
///
/// The scans are copies of the interpreter's helpers in [LiteralSearchKernel],
/// [TrinoLikeWildcardMatcher], and [Utf8], with the same behavior. Generated code does
/// not share the originals because C2 compiles a shared helper from every caller's profile: once
/// generated patterns have run, the helper's compiled code can grow and stop inlining into the
/// interpreter's matchers, which slows interpreted patterns. Keep each copy in step with its
/// original.
final class TrinoLikeKernelSupport
{
    private static final VarHandle SHORT = MethodHandles.byteArrayViewVarHandle(short[].class, ByteOrder.LITTLE_ENDIAN);
    private static final VarHandle INT = MethodHandles.byteArrayViewVarHandle(int[].class, ByteOrder.LITTLE_ENDIAN);
    private static final VarHandle LONG = MethodHandles.byteArrayViewVarHandle(long[].class, ByteOrder.LITTLE_ENDIAN);

    private TrinoLikeKernelSupport() {}

    // Little-endian reads, as Slice and the literal search read. Literal comparisons sign-extend
    // like the interpreter's, and a generator computes its constants with the same reads, so a
    // kernel compares against them directly. The candidate scans rely on the byte order: the
    // lowest set byte of a match mask is the earliest candidate.

    static int readShort(byte[] bytes, int offset)
    {
        return (short) SHORT.get(bytes, offset);
    }

    static int readInt(byte[] bytes, int offset)
    {
        return (int) INT.get(bytes, offset);
    }

    static long readLong(byte[] bytes, int offset)
    {
        return (long) LONG.get(bytes, offset);
    }

    /// A copy of `Utf8.characterWidth`: the width of the character starting at
    /// `index`, which must be before `end`, reading each maximal subpart of malformed
    /// input as one character.
    static int characterWidth(byte[] bytes, int index, int end)
    {
        int b0 = bytes[index] & 0xFF;
        if (b0 < 0x80) {
            return 1;
        }
        if (b0 < 0xC2 || index + 1 >= end) {
            return 1;
        }
        int b1 = bytes[index + 1] & 0xFF;
        if ((b1 & 0xC0) != 0x80) {
            return 1;
        }
        if (b0 < 0xE0) {
            return 2;
        }
        if (b0 < 0xF0) {
            // After E0 a continuation byte below A0 would be overlong; after ED one above 9F, a surrogate.
            if ((b0 == 0xE0 && b1 < 0xA0) || (b0 == 0xED && b1 > 0x9F)) {
                return 1;
            }
            return index + 2 < end && (bytes[index + 2] & 0xC0) == 0x80 ? 3 : 2;
        }
        // After F0 a continuation byte below 90 would be overlong; after F4 one above 8F, beyond U+10FFFF.
        if (b0 > 0xF4 || (b0 == 0xF0 && b1 < 0x90) || (b0 == 0xF4 && b1 > 0x8F)) {
            return 1;
        }
        if (index + 2 >= end || (bytes[index + 2] & 0xC0) != 0x80) {
            return 2;
        }
        return index + 3 < end && (bytes[index + 3] & 0xC0) == 0x80 ? 4 : 3;
    }

    /// A copy of `TrinoLikeWildcardMatcher.nonAsciiCodePoint`: the code point of the
    /// non-ASCII character of `width` bytes at `position`, or
    /// [Integer#MIN_VALUE], which equals no literal, for a maximal subpart of malformed input.
    static int nonAsciiCodePoint(byte[] input, int position, int width)
    {
        int header = input[position] & 0xFF;
        if (width == 2 && header < 0xE0) {
            return ((header & 0b0001_1111) << 6) | (input[position + 1] & 0b0011_1111);
        }
        if (width == 3 && header < 0xF0) {
            return ((header & 0b0000_1111) << 12) |
                    ((input[position + 1] & 0b0011_1111) << 6) |
                    (input[position + 2] & 0b0011_1111);
        }
        if (width == 4) {
            return ((header & 0b0000_0111) << 18) |
                    ((input[position + 1] & 0b0011_1111) << 12) |
                    ((input[position + 2] & 0b0011_1111) << 6) |
                    (input[position + 3] & 0b0011_1111);
        }
        return Integer.MIN_VALUE;
    }

    /// A copy of `LiteralSearchKernel.matchingPrefixLength`: how many leading bytes of
    /// `literal` occur at `inputOffset`.
    static int matchingPrefixLength(byte[] input, int inputOffset, byte[] literal)
    {
        int length = literal.length;
        if (length >= Long.BYTES) {
            int index = 0;
            for (; index < length - Long.BYTES; index += Long.BYTES) {
                long difference = ((long) LONG.get(input, inputOffset + index)) ^ ((long) LONG.get(literal, index));
                if (difference != 0) {
                    return index + (Long.numberOfTrailingZeros(difference) >>> 3);
                }
            }
            index = length - Long.BYTES;
            long difference = ((long) LONG.get(input, inputOffset + index)) ^ ((long) LONG.get(literal, index));
            return difference == 0 ? length : index + (Long.numberOfTrailingZeros(difference) >>> 3);
        }
        if (length >= Integer.BYTES) {
            int difference = ((int) INT.get(input, inputOffset)) ^ ((int) INT.get(literal, 0));
            if (difference != 0) {
                return Integer.numberOfTrailingZeros(difference) >>> 3;
            }
            int index = length - Integer.BYTES;
            difference = ((int) INT.get(input, inputOffset + index)) ^ ((int) INT.get(literal, index));
            return difference == 0 ? length : index + (Integer.numberOfTrailingZeros(difference) >>> 3);
        }
        for (int index = 0; index < length; index++) {
            if (input[inputOffset + index] != literal[index]) {
                return index;
            }
        }
        return length;
    }

    /// A copy of `LiteralSearchKernel.findKmp`: the first position in
    /// `[searchStart, searchEnd)` where the whole `literal` occurs, or `-1`.
    static int findKmp(byte[] input, int searchStart, int searchEnd, byte[] literal, int[] prefixShifts)
    {
        int matchedLength = 0;
        for (int position = searchStart; position < searchEnd; position++) {
            while (matchedLength >= 0 && input[position] != literal[matchedLength]) {
                matchedLength = prefixShifts[matchedLength];
            }
            matchedLength++;
            if (matchedLength == literal.length) {
                return position - literal.length + 1;
            }
        }
        return -1;
    }
}
