// Compilation through the public API, the meta engine, and the syntax crate

/// The public API: `regex::Regex` searches `&str`, and `regex::bytes::Regex`
/// searches `&[u8]`.
enum PublicRegex {
    String(regex::Regex),
    Bytes(regex::bytes::Regex),
}

impl PublicRegex {
    fn captures_len(&self) -> usize {
        match self {
            PublicRegex::String(regex) => regex.captures_len(),
            PublicRegex::Bytes(regex) => regex.captures_len(),
        }
    }

    fn capture_names(&self) -> Vec<Option<String>> {
        match self {
            PublicRegex::String(regex) => regex
                .capture_names()
                .map(|name| name.map(str::to_string))
                .collect(),
            PublicRegex::Bytes(regex) => regex
                .capture_names()
                .map(|name| name.map(str::to_string))
                .collect(),
        }
    }
}

/// Applies the settings the front end exposes, identically for both builders.
macro_rules! configure_builder {
    ($builder:expr, $options:expr) => {
        $builder
            .case_insensitive($options.case_insensitive)
            .multi_line($options.multi_line)
            .dot_matches_new_line($options.dot_matches_new_line)
            .crlf($options.crlf)
            .swap_greed($options.swap_greed)
            .ignore_whitespace($options.ignore_whitespace)
            .octal($options.octal)
            .nest_limit($options.nest_limit)
            .unicode(!$options.unicode_disabled)
    };
}

fn build_public(pattern: &str, options: Options) -> Result<PublicRegex, regex::Error> {
    if options.bytes {
        configure_builder!(regex::bytes::RegexBuilder::new(pattern), options)
            .build()
            .map(PublicRegex::Bytes)
    } else {
        configure_builder!(regex::RegexBuilder::new(pattern), options)
            .build()
            .map(PublicRegex::String)
    }
}

/// The meta configuration `regex` 1.13.1 `Builder::build_one_string` uses,
/// or `Builder::build_one_bytes` for the bytes API.
fn meta_config(options: Options) -> meta::Config {
    meta::Config::new()
        .nfa_size_limit(Some(NFA_SIZE_LIMIT))
        .hybrid_cache_capacity(HYBRID_CACHE_CAPACITY)
        .match_kind(MatchKind::LeftmostFirst)
        .utf8_empty(!options.bytes)
}

/// The syntax configuration `regex` 1.13.1 `Builder::build_one_string` uses,
/// or `Builder::build_one_bytes` for the bytes API.
fn syntax_config(options: Options) -> automata_syntax::Config {
    automata_syntax::Config::new()
        .case_insensitive(options.case_insensitive)
        .multi_line(options.multi_line)
        .dot_matches_new_line(options.dot_matches_new_line)
        .crlf(options.crlf)
        .swap_greed(options.swap_greed)
        .ignore_whitespace(options.ignore_whitespace)
        .octal(options.octal)
        .nest_limit(options.nest_limit)
        .unicode(!options.unicode_disabled)
        .utf8(!options.bytes)
}

fn build_meta(pattern: &str, options: Options) -> Result<meta::Regex, meta::BuildError> {
    meta::Builder::new()
        .configure(meta_config(options))
        .syntax(syntax_config(options))
        .build(pattern)
}

/// Parses and translates with the syntax crate directly, wired as
/// regex-automata's `syntax::Config::apply_ast` and `apply_hir` wire the meta
/// builder's parser and translator.
fn parse_hir(pattern: &str, options: Options) -> Result<Hir, regex_syntax::Error> {
    let ast = ParserBuilder::new()
        .ignore_whitespace(options.ignore_whitespace)
        .nest_limit(options.nest_limit)
        .octal(options.octal)
        .build()
        .parse(pattern)?;
    let hir = TranslatorBuilder::new()
        .unicode(!options.unicode_disabled)
        .case_insensitive(options.case_insensitive)
        .multi_line(options.multi_line)
        .crlf(options.crlf)
        .dot_matches_new_line(options.dot_matches_new_line)
        .line_terminator(LINE_TERMINATOR)
        .swap_greed(options.swap_greed)
        .utf8(!options.bytes)
        .build()
        .translate(pattern, &ast)?;
    Ok(hir)
}

/// The pattern followed by an end-of-haystack assertion. A full match runs it
/// as an anchored search on the haystack truncated at the window end, so the
/// match must span exactly the window. The parsed `Hir` is wrapped rather than
/// the pattern text, because a verbose-mode comment at the end of a pattern
/// would swallow a textual anchor.
fn build_full(hir: &Hir, options: Options) -> Result<meta::Regex, meta::BuildError> {
    let anchored = Hir::concat(vec![hir.clone(), Hir::look(Look::End)]);
    meta::Builder::new()
        .configure(meta_config(options))
        .build_from_hir(&anchored)
}

/// Whether the pattern contains an assertion that reads the haystack at or
/// after its own position, following regex-automata 0.4.18
/// `util::look::LookMatcher`. Truncating the haystack at a window end changes
/// what such an assertion sees at that end, so a full match of a window that
/// stops short of the haystack end is undefined for these patterns.
fn reads_right_context(hir: &Hir) -> bool {
    hir.properties().look_set().iter().any(|look| match look {
        // `at == 0`, `haystack[at - 1]`, or the decoded character before `at`.
        Look::Start | Look::StartLF | Look::WordStartHalfAscii | Look::WordStartHalfUnicode => {
            false
        }
        // `at == haystack.len()` or `haystack[at..]`.
        Look::End
        | Look::EndLF
        | Look::StartCRLF
        | Look::EndCRLF
        | Look::WordAscii
        | Look::WordAsciiNegate
        | Look::WordUnicode
        | Look::WordUnicodeNegate
        | Look::WordStartAscii
        | Look::WordEndAscii
        | Look::WordStartUnicode
        | Look::WordEndUnicode
        | Look::WordEndHalfAscii
        | Look::WordEndHalfUnicode => true,
    })
}

enum Compiled {
    Accepted {
        public: PublicRegex,
        meta: meta::Regex,
        full: meta::Regex,
        reads_right_context: bool,
    },
    Rejected {
        rejection: Rejection,
        public_error: regex::Error,
    },
}

enum Rejection {
    Syntax(regex_syntax::Error),
    SizeLimit,
}

fn compile(pattern: &str, options: Options) -> Result<Compiled, String> {
    let public = build_public(pattern, options);
    let meta = build_meta(pattern, options);
    let parsed = parse_hir(pattern, options);

    match (public, meta) {
        (Ok(public), Ok(meta)) => {
            let hir = parsed.map_err(|e| {
                format!("syntax crate rejected {pattern:?} with options {} that RegexBuilder accepts: {e}", options.render())
            })?;
            let full = build_full(&hir, options)
                .map_err(|e| format!("full-match regex for {pattern:?} failed to build: {e}"))?;
            if group_len(&full) != public.captures_len() {
                return Err(format!(
                    "full-match regex for {pattern:?} changed the capture group count"
                ));
            }
            Ok(Compiled::Accepted {
                public,
                meta,
                full,
                reads_right_context: reads_right_context(&hir),
            })
        }
        (Err(public_error), Err(meta_error)) => {
            // regex 1.13.1 `Error::from_meta_build_error`.
            let converted = if let Some(limit) = meta_error.size_limit() {
                regex::Error::CompiledTooBig(limit)
            } else if let Some(error) = meta_error.syntax_error() {
                regex::Error::Syntax(error.to_string())
            } else {
                regex::Error::Syntax(meta_error.to_string())
            };
            if converted != public_error {
                return Err(format!(
                    "meta builder error for {pattern:?} differs from RegexBuilder: {converted:?} versus {public_error:?}"
                ));
            }
            let rejection = match &public_error {
                regex::Error::CompiledTooBig(_) => {
                    if let Err(e) = parsed {
                        return Err(format!("RegexBuilder hit the size limit for {pattern:?} but the syntax crate rejected it: {e}"));
                    }
                    Rejection::SizeLimit
                }
                regex::Error::Syntax(_) => {
                    let error = match parsed {
                        Err(error) => error,
                        Ok(_) => {
                            return Err(format!(
                                "RegexBuilder rejected {pattern:?} with options {} but the syntax crate accepts it: {public_error}",
                                options.render()
                            ))
                        }
                    };
                    if meta_error.syntax_error() != Some(&error) {
                        return Err(format!(
                            "syntax crate error for {pattern:?} differs from the meta builder: {error:?} versus {:?}",
                            meta_error.syntax_error()
                        ));
                    }
                    Rejection::Syntax(error)
                }
                other => {
                    return Err(format!(
                        "unexpected RegexBuilder error for {pattern:?}: {other:?}"
                    ))
                }
            };
            Ok(Compiled::Rejected {
                rejection,
                public_error,
            })
        }
        (public, meta) => Err(format!(
            "RegexBuilder and meta builder disagree on {pattern:?}: {:?} versus {:?}",
            public.err(),
            meta.err()
        )),
    }
}

/// Error fields: class, stage, kind, span start, span end.
fn rejection_fields(rejection: &Rejection) -> Result<[Value; 5], String> {
    let (stage, kind, span) = match rejection {
        Rejection::SizeLimit => {
            return Ok([
                Value::string("size_limit"),
                Value::Null,
                Value::Null,
                Value::Null,
                Value::Null,
            ]);
        }
        Rejection::Syntax(regex_syntax::Error::Parse(error)) => {
            ("ast", format!("{:?}", error.kind()), error.span())
        }
        Rejection::Syntax(regex_syntax::Error::Translate(error)) => {
            ("hir", format!("{:?}", error.kind()), error.span())
        }
        Rejection::Syntax(other) => return Err(format!("unknown syntax error variant {other:?}")),
    };
    Ok([
        Value::string("syntax"),
        Value::string(stage),
        Value::string(variant_name(&kind)),
        Value::number(span.start.offset),
        Value::number(span.end.offset),
    ])
}

/// The enum variant name from a derived `Debug` rendering, without payload.
fn variant_name(debug: &str) -> &str {
    let end = debug
        .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .unwrap_or(debug.len());
    &debug[..end]
}

