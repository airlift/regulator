// JSON output limited to what the Java GoldenJsonl reader parses: strings,
// booleans, and null. Numbers are written as decimal strings.

enum Value {
    String(String),
    Bool(bool),
    Null,
}

impl Value {
    fn string(value: &str) -> Value {
        Value::String(value.to_string())
    }

    fn number(value: usize) -> Value {
        Value::String(value.to_string())
    }
}

fn json_object(fields: &[(&str, Value)]) -> String {
    let mut out = String::from("{");
    for (index, (key, value)) in fields.iter().enumerate() {
        if index > 0 {
            out.push(',');
        }
        json_string(key, &mut out);
        out.push(':');
        match value {
            Value::String(value) => json_string(value, &mut out),
            Value::Bool(value) => out.push_str(if *value { "true" } else { "false" }),
            Value::Null => out.push_str("null"),
        }
    }
    out.push('}');
    out
}

/// Writes ASCII-only JSON, escaping everything else as UTF-16 `\u` units.
fn json_string(value: &str, out: &mut String) {
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_ascii() && !c.is_ascii_control() => out.push(c),
            c => {
                for unit in c.encode_utf16(&mut [0; 2]) {
                    write!(out, "\\u{unit:04x}").expect("writing to a String cannot fail");
                }
            }
        }
    }
    out.push('"');
}
