fn format_groups(groups: &Groups) -> String {
    groups
        .iter()
        .map(|group| match group {
            Some((start, end)) => format!("{start}:{end}"),
            None => "-1:-1".to_string(),
        })
        .collect::<Vec<_>>()
        .join(",")
}

fn optional_groups(groups: &Option<Groups>) -> Value {
    groups
        .as_ref()
        .map_or(Value::Null, |groups| Value::string(&format_groups(groups)))
}

/// Result fields shared by the match and upstream fixtures. Only windowed
/// records carry `fullDefined`, because only a window can leave the full match
/// undefined.
fn result_fields(
    fields: &mut Vec<(&'static str, Value)>,
    compiled: &Compiled,
    observed: Option<&Observed>,
    windowed: bool,
) -> Result<(), String> {
    match (compiled, observed) {
        (Compiled::Accepted { .. }, Some(observed)) => {
            let search = &observed.search;
            fields.push(("ok", Value::Bool(true)));
            push_error_fields(fields, None)?;
            push_group_fields(fields, search.group_count, &search.group_names);
            fields.push(("isMatch", Value::Bool(search.is_match)));
            fields.push(("captures", optional_groups(&search.captures)));
            fields.push(("matchCount", Value::number(search.matches.len())));
            fields.push((
                "matches",
                Value::string(
                    &search
                        .matches
                        .iter()
                        .take(MAX_RECORDED_MATCHES)
                        .map(format_groups)
                        .collect::<Vec<_>>()
                        .join(";"),
                ),
            ));
            fields.push(("anchoredCaptures", optional_groups(&observed.anchored)));
            if windowed {
                fields.push(("fullDefined", Value::Bool(observed.full.is_some())));
            } else if observed.full.is_none() {
                return Err("internal error: full match undefined without a window".to_string());
            }
            fields.push((
                "fullCaptures",
                optional_groups(&observed.full.clone().flatten()),
            ));
        }
        (Compiled::Rejected { rejection, .. }, None) => {
            fields.push(("ok", Value::Bool(false)));
            push_error_fields(fields, Some(rejection))?;
            for key in [
                "groupCount",
                "groupNames",
                "isMatch",
                "captures",
                "matchCount",
                "matches",
                "anchoredCaptures",
            ] {
                fields.push((key, Value::Null));
            }
            if windowed {
                fields.push(("fullDefined", Value::Null));
            }
            fields.push(("fullCaptures", Value::Null));
        }
        _ => return Err("internal error: observation does not match compilation".to_string()),
    }
    Ok(())
}

fn push_error_fields(
    fields: &mut Vec<(&'static str, Value)>,
    rejection: Option<&Rejection>,
) -> Result<(), String> {
    let values = match rejection {
        Some(rejection) => rejection_fields(rejection)?,
        None => [
            Value::Null,
            Value::Null,
            Value::Null,
            Value::Null,
            Value::Null,
        ],
    };
    for (key, value) in ["error", "errorStage", "errorKind", "errorStart", "errorEnd"]
        .into_iter()
        .zip(values)
    {
        fields.push((key, value));
    }
    Ok(())
}

/// Group count includes group zero. Names are listed in group index order,
/// with `-` for an unnamed group; names cannot contain `-` or `,`.
fn push_group_fields(
    fields: &mut Vec<(&'static str, Value)>,
    group_count: usize,
    group_names: &[Option<String>],
) {
    let names = group_names
        .iter()
        .map(|name| name.as_deref().unwrap_or("-"))
        .collect::<Vec<_>>()
        .join(",");
    fields.push(("groupCount", Value::number(group_count)));
    fields.push(("groupNames", Value::string(&names)));
}

