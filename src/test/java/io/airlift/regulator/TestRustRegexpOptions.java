package io.airlift.regulator;

import org.junit.jupiter.api.Test;

import static io.airlift.slice.Slices.utf8Slice;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

public class TestRustRegexpOptions
{
    @Test
    public void testCompilationSnapshotsOptions()
    {
        RustRegexp.Options options = RustRegexp.Options.defaults().setCaseInsensitive(true);
        RustRegexp regexp = RustRegexp.compile(utf8Slice("abc"), options);

        options.setCaseInsensitive(false);

        assertThat(regexp.matches(utf8Slice("ABC"))).isTrue();

        // The compiled scan plan's leading-literal probe, chosen by the distribution at
        // compilation, is retained; the prefix scan of the same pattern keeps the first byte.
        options = RustRegexp.Options.defaults().setByteFrequencies(TestingByteFrequencies.learnedJsonRecords());
        regexp = RustRegexp.compile(utf8Slice("été=([a-z]+)"), options);

        options.setByteFrequencies(ByteFrequencies.uniform());

        assertThat(regexp.pattern().caseSensitiveTrinoScanPlan().leadingLiteralProbeOffsetForDiagnostics()).isEqualTo(5);
        assertThat(regexp.pattern().forwardProgramForDiagnostics().prefixAccelProbeOffset()).isZero();
        Re2 uniform = RustRegexp.compile(utf8Slice("été=([a-z]+)"), options).pattern();
        assertThat(uniform.caseSensitiveTrinoScanPlan().leadingLiteralProbeOffsetForDiagnostics()).isZero();
        assertThat(uniform.forwardProgramForDiagnostics().prefixAccelProbeOffset()).isZero();

        // The compiled probe offset, chosen by the distribution at compilation, is retained.
        options = RustRegexp.Options.defaults().setByteFrequencies(TestingByteFrequencies.rareNonLetters());
        regexp = RustRegexp.compile(utf8Slice("https://(\\S+)"), options);

        options.setByteFrequencies(ByteFrequencies.uniform());

        assertThat(regexp.pattern().forwardProgramForDiagnostics().prefixAccelProbeOffset()).isEqualTo(5);
        assertThat(RustRegexp.compile(utf8Slice("https://(\\S+)"), options).pattern().forwardProgramForDiagnostics().prefixAccelProbeOffset()).isZero();

        // Generated bytecode is decided at compilation and is off by default.
        options = RustRegexp.Options.defaults().setGenerateBytecode(true);
        regexp = RustRegexp.compile(utf8Slice("^https?://([^/]+)/"), options);

        options.setGenerateBytecode(false);

        assertThat(regexp.usesGeneratedBytecode()).isTrue();
        assertThat(RustRegexp.compile(utf8Slice("^https?://([^/]+)/"), options).usesGeneratedBytecode()).isFalse();
        assertThat(RustRegexp.compile(utf8Slice("^https?://([^/]+)/")).usesGeneratedBytecode()).isFalse();
    }

    @Test
    public void testNestLimit()
    {
        assertThat(RustRegexp.Options.defaults().nestLimit()).isEqualTo(250);
        assertThatThrownBy(() -> RustRegexp.Options.defaults().setNestLimit(-1))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessage("nestLimit must not be negative: -1");
    }

    @Test
    public void testNestLimitAboveDefault()
    {
        // Every phase walks this nesting with its own stack rather than the thread stack.
        RustRegexp.Options options = RustRegexp.Options.defaults().setNestLimit(100_000);
        RustRegexp nested = RustRegexp.compile(utf8Slice("(?:".repeat(100_000) + "a" + ")".repeat(100_000)), options);

        assertThat(nested.matches(utf8Slice("a"))).isTrue();
    }

    @Test
    public void testMemoryBudget()
    {
        assertThat(RustRegexp.Options.defaults().maxMemory()).isEqualTo(96L << 20);
        assertThatThrownBy(() -> RustRegexp.Options.defaults().setMaxMemory(0))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("greater than zero");
        assertThatThrownBy(() -> RustRegexp.compile(
                utf8Slice("abc"),
                RustRegexp.Options.defaults().setMaxMemory(1)))
                .isInstanceOf(RegexpCompileMemoryLimitException.class);
    }

    @Test
    public void testByteFrequencies()
    {
        assertThat(RustRegexp.Options.defaults().byteFrequencies()).isSameAs(ByteFrequencies.uniform());
        assertThatThrownBy(() -> RustRegexp.Options.defaults().setByteFrequencies(null))
                .isInstanceOf(NullPointerException.class)
                .hasMessage("byteFrequencies is null");
    }
}
