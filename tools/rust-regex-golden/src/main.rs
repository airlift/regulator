/// The `RegexBuilder` settings the front end exposes. Unicode is on by
/// default and the nest limit defaults to the crate's. `bytes` selects
/// `regex::bytes::RegexBuilder` instead of `regex::RegexBuilder`.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct Options {
    case_insensitive: bool,
    multi_line: bool,
    dot_matches_new_line: bool,
    crlf: bool,
    swap_greed: bool,
    ignore_whitespace: bool,
    octal: bool,
    unicode_disabled: bool,
    nest_limit: u32,
    bytes: bool,
}

impl Default for Options {
    fn default() -> Options {
        Options {
            case_insensitive: false,
            multi_line: false,
            dot_matches_new_line: false,
            crlf: false,
            swap_greed: false,
            ignore_whitespace: false,
            octal: false,
            unicode_disabled: false,
            nest_limit: DEFAULT_NEST_LIMIT,
            bytes: false,
        }
    }
}

impl Options {
    /// Parses `-` for defaults, or comma-separated groups in this order:
    /// enabled flags from `imsRUxo` in that order, `-u` to disable Unicode,
    /// `n` followed by a nest limit other than the default, and `bytes` for
    /// the bytes API.
    fn parse(field: &str) -> Result<Options, String> {
        let mut options = Options::default();
        if field != "-" {
            for part in field.split(',') {
                if part == "-u" {
                    options.unicode_disabled = true;
                    continue;
                }
                if part == "bytes" {
                    options.bytes = true;
                    continue;
                }
                if let Some(limit) = part.strip_prefix('n') {
                    options.nest_limit = limit
                        .parse()
                        .map_err(|_| format!("invalid nest limit {limit:?} in {field:?}"))?;
                    continue;
                }
                if part.is_empty() {
                    return Err(format!("empty option group in {field:?}"));
                }
                for flag in part.chars() {
                    let enabled = match flag {
                        'i' => &mut options.case_insensitive,
                        'm' => &mut options.multi_line,
                        's' => &mut options.dot_matches_new_line,
                        'R' => &mut options.crlf,
                        'U' => &mut options.swap_greed,
                        'x' => &mut options.ignore_whitespace,
                        'o' => &mut options.octal,
                        _ => return Err(format!("unknown option {flag:?} in {field:?}")),
                    };
                    *enabled = true;
                }
            }
        }
        if options.render() != field {
            return Err(format!(
                "options {field:?} are not in canonical form {:?}",
                options.render()
            ));
        }
        Ok(options)
    }

    fn render(&self) -> String {
        let mut enabled = String::new();
        for (flag, set) in [
            ('i', self.case_insensitive),
            ('m', self.multi_line),
            ('s', self.dot_matches_new_line),
            ('R', self.crlf),
            ('U', self.swap_greed),
            ('x', self.ignore_whitespace),
            ('o', self.octal),
        ] {
            if set {
                enabled.push(flag);
            }
        }
        let mut groups = Vec::new();
        if !enabled.is_empty() {
            groups.push(enabled);
        }
        if self.unicode_disabled {
            groups.push("-u".to_string());
        }
        if self.nest_limit != DEFAULT_NEST_LIMIT {
            groups.push(format!("n{}", self.nest_limit));
        }
        if self.bytes {
            groups.push("bytes".to_string());
        }
        if groups.is_empty() {
            return "-".to_string();
        }
        groups.join(",")
    }
}

