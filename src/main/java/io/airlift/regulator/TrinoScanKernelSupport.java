package io.airlift.regulator;

import io.airlift.regulator.TrinoScanPlan.Step;

import java.lang.invoke.MethodHandles;
import java.lang.invoke.VarHandle;
import java.nio.ByteOrder;
import java.util.Arrays;

import static io.airlift.regulator.TrinoScanPlanRun.CANDIDATE_SCAN_NIBBLE_TABLE;
import static io.airlift.regulator.TrinoScanPlanRun.CANDIDATE_SCAN_RANGE;
import static io.airlift.regulator.TrinoScanPlanRun.CANDIDATE_SCAN_SMALL_SET;
import static io.airlift.regulator.TrinoScanPlanRun.RE2_RUN_STOP_MINIMUM_BYTES;
import static io.airlift.regulator.TrinoScanPlanRun.SCALAR_CANDIDATE_PREFIX_BYTES;

/**
 * The helpers that classes generated by {@link TrinoScanKernelGenerator} call.
 * <p>
 * The scans are copies of the interpreter's helpers in {@link TrinoScanPlan},
 * {@link TrinoScanPlanRun}, and {@link Utf8}, with the same behavior; their vector loops are in
 * {@link VectorTrinoScanKernelSupport}. Generated code does not share the originals because C2
 * compiles a shared helper from every caller's profile: once generated patterns have run, the
 * helper's compiled code is larger and no longer inlines into the interpreter's attempt methods,
 * which slows interpreted patterns. Keep each copy in step with its original.
 */
final class TrinoScanKernelSupport
{
    private static final VarHandle SHORT = MethodHandles.byteArrayViewVarHandle(short[].class, ByteOrder.nativeOrder());
    private static final VarHandle INT = MethodHandles.byteArrayViewVarHandle(int[].class, ByteOrder.nativeOrder());
    private static final VarHandle LONG = MethodHandles.byteArrayViewVarHandle(long[].class, ByteOrder.nativeOrder());

    private TrinoScanKernelSupport() {}

    // Native-order reads for generated literal comparisons. Each read is sign-extended like the
    // interpreter's, so a kernel compares against the plan's constants.

    static int readShort(byte[] bytes, int offset)
    {
        return (short) SHORT.get(bytes, offset);
    }

    static int readInt(byte[] bytes, int offset)
    {
        return (int) INT.get(bytes, offset);
    }

    static long readLong(byte[] bytes, int offset)
    {
        return (long) LONG.get(bytes, offset);
    }

    /**
     * A copy of {@code TrinoScanPlan.findByte}.
     */
    static int findByte(byte[] bytes, int cursor, int end, byte target)
    {
        if (VectorSupport.isAvailable()) {
            return VectorTrinoScanKernelSupport.findByte(bytes, cursor, end, target);
        }
        for (; cursor < end; cursor++) {
            if (bytes[cursor] == target) {
                return cursor;
            }
        }
        return -1;
    }

    /**
     * A copy of {@code TrinoScanPlan.findLiteral}: the first position at or after
     * {@code candidate} where the whole {@code literal} occurs, or {@code -1} when none remains.
     */
    static int findLiteral(byte[] bytes, int candidate, int end, byte[] literal)
    {
        // A start after this limit leaves too few bytes for the literal.
        int limit = end - literal.length + 1;
        while ((candidate = findByte(bytes, candidate, limit, literal[0])) >= 0) {
            int index = 1;
            while (index < literal.length && bytes[candidate + index] == literal[index]) {
                index++;
            }
            if (index == literal.length) {
                return candidate;
            }
            candidate++;
        }
        return -1;
    }

    /**
     * A copy of {@code TrinoScanPlan.findLiteralAtProbe}: {@link #findLiteral}, scanning for the
     * byte at {@code probeOffset}, which is not zero.
     */
    static int findLiteralAtProbe(byte[] bytes, int candidate, int end, byte[] literal, int probeOffset)
    {
        byte probe = literal[probeOffset];
        // A start after this limit leaves too few bytes for the literal, and the probe byte of a
        // start before it lies before end.
        int limit = end - literal.length + 1;
        // Shifting a start past the limit by the probe offset can overflow at the end of a
        // backing array near the int limit.
        if (candidate >= limit) {
            return -1;
        }
        int found;
        while ((found = findByte(bytes, candidate + probeOffset, limit + probeOffset, probe)) >= 0) {
            candidate = found - probeOffset;
            // The scan has already compared the probe byte.
            int index = 0;
            while (index < probeOffset && bytes[candidate + index] == literal[index]) {
                index++;
            }
            if (index == probeOffset) {
                index++;
                while (index < literal.length && bytes[candidate + index] == literal[index]) {
                    index++;
                }
                if (index == literal.length) {
                    return candidate;
                }
            }
            candidate++;
        }
        return -1;
    }

    /**
     * A copy of {@code TrinoScanPlan.containsRequiredLiteral}, for the plan's required
     * {@code literal}.
     */
    static boolean containsRequiredLiteral(byte[] bytes, int cursor, int end, Step literal)
    {
        if (VectorSupport.isAvailable()) {
            return VectorTrinoScanKernelSupport.containsLiteral(bytes, cursor, end, literal);
        }
        int lastStart = end - literal.literal.length;
        for (; cursor <= lastStart; cursor++) {
            if (literalMatches(literal, bytes, cursor, end)) {
                return true;
            }
        }
        return false;
    }

    /**
     * A copy of {@code TrinoScanPlan.Step.matches}.
     */
    static boolean literalMatches(Step step, byte[] input, int cursor, int end)
    {
        byte[] literal = step.literal;
        if (literal.length > end - cursor) {
            return false;
        }
        if (literal.length > 2 * Long.BYTES) {
            return Arrays.mismatch(literal, 0, literal.length, input, cursor, cursor + literal.length) < 0;
        }
        long first = step.first();
        long last = step.last();
        int lastOffset = step.lastOffset();
        return switch (step.width()) {
            case 1 -> input[cursor] == first;
            case 2 -> ((readShort(input, cursor) ^ first) | (readShort(input, cursor + lastOffset) ^ last)) == 0;
            case 4 -> ((readInt(input, cursor) ^ first) | (readInt(input, cursor + lastOffset) ^ last)) == 0;
            case 8 -> ((readLong(input, cursor) ^ first) | (readLong(input, cursor + lastOffset) ^ last)) == 0;
            default -> throw new IllegalStateException("unexpected literal width: " + step.width());
        };
    }

    /**
     * A copy of {@code TrinoScanPlanRun.match}.
     */
    static int runMatch(TrinoScanPlanRun run, byte[] input, int cursor, int end)
    {
        int minimum = run.minimum();
        int maximum = run.maximum();
        if (!run.matchesNonAscii()) {
            int limit = maximum < 0 ? end : cursor + Math.min(maximum, end - cursor);
            int stop = runScan(run, input, cursor, limit);
            return stop - cursor >= minimum ? stop : -1;
        }
        if (maximum < 0 && minimum <= 1) {
            int stop = runScan(run, input, cursor, end);
            return stop - cursor >= minimum ? stop : -1;
        }
        // Finite bounds count characters, not encoded bytes. For an unbounded run, decode
        // only enough characters to prove its minimum, then resume the byte scan.
        boolean[] members = run.members();
        int count = 0;
        int limit = maximum < 0 ? minimum : maximum;
        while (count < limit && cursor < end && members[input[cursor] & 0xFF]) {
            cursor += Utf8.decodedWidth(decode(input, cursor, end));
            count++;
        }
        if (count < minimum) {
            return -1;
        }
        return maximum < 0 ? runScan(run, input, cursor, end) : cursor;
    }

    /**
     * A copy of {@code TrinoScanPlanRun.matchMinimum}.
     */
    static int runMatchMinimum(TrinoScanPlanRun run, byte[] input, int cursor, int end)
    {
        int minimum = run.minimum();
        boolean[] members = run.members();
        boolean matchesNonAscii = run.matchesNonAscii();
        for (int count = 0; count < minimum; count++) {
            if (cursor >= end || !members[input[cursor] & 0xFF]) {
                return -1;
            }
            cursor += matchesNonAscii ? Utf8.decodedWidth(decode(input, cursor, end)) : 1;
        }
        return cursor;
    }

    /**
     * A copy of {@code TrinoScanPlanRun.re2Match}.
     */
    static int re2RunMatch(TrinoScanPlanRun run, byte[] input, int cursor, int end)
    {
        int minimum = run.minimum();
        int maximum = run.maximum();
        if (maximum < 0 && minimum <= 1) {
            int stop = re2RunScan(run, input, cursor, end);
            return stop - cursor >= minimum ? stop : -1;
        }
        int count = 0;
        int limit = maximum < 0 ? minimum : maximum;
        int width;
        while (count < limit && (width = re2RunMemberWidth(run, input, cursor, end)) != 0) {
            cursor += width;
            count++;
        }
        if (count < minimum) {
            return -1;
        }
        return maximum < 0 ? re2RunScan(run, input, cursor, end) : cursor;
    }

    /**
     * A copy of {@code TrinoScanPlanRun.re2MatchMinimum}.
     */
    static int re2RunMatchMinimum(TrinoScanPlanRun run, byte[] input, int cursor, int end)
    {
        int minimum = run.minimum();
        for (int count = 0; count < minimum; count++) {
            int width = re2RunMemberWidth(run, input, cursor, end);
            if (width == 0) {
                return -1;
            }
            cursor += width;
        }
        return cursor;
    }

    /**
     * A copy of {@code TrinoScanPlanRun.re2MatchBefore}.
     */
    static int re2RunMatchBefore(TrinoScanPlanRun run, byte[] input, int cursor, int end, byte delimiter)
    {
        int stop = re2RunMatch(run, input, cursor, end);
        return stop >= 0 && stop < end && input[stop] == delimiter ? stop : -1;
    }

    // A copy of TrinoScanPlanRun.re2MemberWidth.
    private static int re2RunMemberWidth(TrinoScanPlanRun run, byte[] input, int cursor, int end)
    {
        if (cursor >= end) {
            return 0;
        }
        int value = input[cursor];
        if (value < 0) {
            return re2CharacterWidth(input, cursor, end);
        }
        return run.members()[value] ? 1 : 0;
    }

    // A copy of TrinoScanPlanRun.re2Scan.
    private static int re2RunScan(TrinoScanPlanRun run, byte[] input, int cursor, int end)
    {
        byte[] needles = run.needles();
        boolean[] members = run.members();
        while (true) {
            // Find the first non-member ASCII byte or non-ASCII byte, then consume the
            // non-ASCII characters there. Less than a vector of input is scanned by byte, as
            // Trino's run scan does for its tail.
            if (needles != null && end - cursor >= RE2_RUN_STOP_MINIMUM_BYTES && VectorSupport.isAvailable()) {
                cursor = VectorTrinoScanKernelSupport.findRe2RunStop(input, cursor, end, needles);
            }
            else if (needles != null && needles.length == 0) {
                // Every ASCII byte is a member.
                while (cursor < end && input[cursor] >= 0) {
                    cursor++;
                }
            }
            else {
                while (cursor < end && input[cursor] >= 0 && members[input[cursor]]) {
                    cursor++;
                }
            }
            int width;
            while (cursor < end && input[cursor] < 0 && (width = re2CharacterWidth(input, cursor, end)) != 0) {
                cursor += width;
            }
            if (cursor >= end || input[cursor] < 0 || !members[input[cursor]]) {
                return cursor;
            }
        }
    }

    // A copy of TrinoScanPlanRun.scan.
    private static int runScan(TrinoScanPlanRun run, byte[] input, int cursor, int end)
    {
        byte[] needles = run.needles();
        boolean[] members = run.members();
        if (needles != null) {
            if (needles.length == 0) {
                return run.isInverted() ? end : cursor;
            }
            if (VectorSupport.isAvailable()) {
                return VectorTrinoScanKernelSupport.findRunStop(input, cursor, end, needles, run.isInverted(), members);
            }
        }
        for (; cursor < end; cursor++) {
            if (!members[input[cursor] & 0xFF]) {
                return cursor;
            }
        }
        return end;
    }

    /**
     * A copy of {@code TrinoScanPlanRun.findCandidate}.
     */
    static int runFindCandidate(TrinoScanPlanRun run, byte[] input, int cursor, int end)
    {
        boolean[] members = run.members();
        int candidateScan = run.candidateScan();
        // Dense inputs usually have a candidate at the cursor, and large sets such as word
        // characters within a few bytes, where vector setup costs more than it saves.
        int scalarEnd = Math.min(end, cursor + (candidateScan == CANDIDATE_SCAN_NIBBLE_TABLE ? SCALAR_CANDIDATE_PREFIX_BYTES : 1));
        for (; cursor < scalarEnd; cursor++) {
            if (members[input[cursor] & 0xFF]) {
                return cursor;
            }
        }
        if (cursor >= end) {
            return -1;
        }
        switch (candidateScan) {
            case CANDIDATE_SCAN_SMALL_SET -> {
                byte[] needles = run.needles();
                return VectorTrinoScanKernelSupport.findByteSet(
                        input,
                        cursor,
                        end - cursor,
                        needles[0],
                        needles.length > 1 ? needles[1] : needles[0],
                        needles.length > 2 ? needles[2] : needles[0],
                        needles.length);
            }
            case CANDIDATE_SCAN_RANGE -> {
                return VectorTrinoScanKernelSupport.findRange(input, cursor, end - cursor, run.lowestMember(), run.highestMember());
            }
            case CANDIDATE_SCAN_NIBBLE_TABLE -> {
                return VectorTrinoScanKernelSupport.findNibbleTable(input, cursor, end - cursor, run.candidateNibbleTables());
            }
            default -> {
                return runFindCandidateInTable(run, input, cursor, end);
            }
        }
    }

    // A copy of TrinoScanPlanRun.findCandidateInTable.
    private static int runFindCandidateInTable(TrinoScanPlanRun run, byte[] input, int cursor, int end)
    {
        byte[] needles = run.needles();
        boolean[] members = run.members();
        if (needles != null) {
            if (needles.length == 0) {
                return run.isInverted() ? cursor : -1;
            }
            if (VectorSupport.isAvailable()) {
                return VectorTrinoScanKernelSupport.findRunCandidate(input, cursor, end, needles, run.isInverted(), members);
            }
        }
        for (; cursor < end; cursor++) {
            if (members[input[cursor] & 0xFF]) {
                return cursor;
            }
        }
        return -1;
    }

    /**
     * A copy of {@code Utf8.decode}.
     */
    static long decode(byte[] bytes, int index, int end)
    {
        if (index >= end) {
            return pack(0, 0);
        }

        int b0 = bytes[index] & 0xFF;
        if (b0 < 0x80) {
            return pack(b0, 1);
        }

        // Reject invalid leading bytes and overlong 2-byte sequences.
        if (b0 < 0xC2) {
            return pack(Utf8.RUNE_ERROR, 1);
        }

        if (b0 < 0xE0) {
            if (index + 1 >= end) {
                return pack(Utf8.RUNE_ERROR, 1);
            }
            int b1 = bytes[index + 1] & 0xFF;
            if ((b1 & 0xC0) != 0x80) {
                return pack(Utf8.RUNE_ERROR, 1);
            }
            int codePoint = ((b0 & 0x1F) << 6) | (b1 & 0x3F);
            return pack(codePoint, 2);
        }

        if (b0 < 0xF0) {
            if (index + 2 >= end) {
                return pack(Utf8.RUNE_ERROR, 1);
            }
            int b1 = bytes[index + 1] & 0xFF;
            int b2 = bytes[index + 2] & 0xFF;
            if (((b1 & 0xC0) != 0x80) || ((b2 & 0xC0) != 0x80)) {
                return pack(Utf8.RUNE_ERROR, 1);
            }
            int codePoint = ((b0 & 0x0F) << 12) | ((b1 & 0x3F) << 6) | (b2 & 0x3F);
            // Reject overlongs and surrogates.
            if (codePoint < 0x800 || (codePoint >= 0xD800 && codePoint <= 0xDFFF)) {
                return pack(Utf8.RUNE_ERROR, 1);
            }
            return pack(codePoint, 3);
        }

        if (b0 < 0xF5) {
            if (index + 3 >= end) {
                return pack(Utf8.RUNE_ERROR, 1);
            }
            int b1 = bytes[index + 1] & 0xFF;
            int b2 = bytes[index + 2] & 0xFF;
            int b3 = bytes[index + 3] & 0xFF;
            if (((b1 & 0xC0) != 0x80) || ((b2 & 0xC0) != 0x80) || ((b3 & 0xC0) != 0x80)) {
                return pack(Utf8.RUNE_ERROR, 1);
            }
            int codePoint = ((b0 & 0x07) << 18) | ((b1 & 0x3F) << 12) | ((b2 & 0x3F) << 6) | (b3 & 0x3F);
            // Reject overlongs and outside Unicode range.
            if (codePoint < 0x10000 || codePoint > 0x10FFFF) {
                return pack(Utf8.RUNE_ERROR, 1);
            }
            return pack(codePoint, 4);
        }

        return pack(Utf8.RUNE_ERROR, 1);
    }

    // A copy of Utf8.re2CharacterWidth.
    private static int re2CharacterWidth(byte[] bytes, int index, int end)
    {
        int b0 = bytes[index] & 0xFF;
        if (b0 < 0xC2 || b0 > 0xF4) {
            return 0;
        }
        int width = b0 < 0xE0 ? 2 : b0 < 0xF0 ? 3 : 4;
        if (width > end - index) {
            return 0;
        }
        for (int offset = 1; offset < width; offset++) {
            if ((bytes[index + offset] & 0xC0) != 0x80) {
                return 0;
            }
        }
        return width;
    }

    // A copy of Utf8.pack.
    private static long pack(int codePoint, int width)
    {
        return (((long) width) << 32) | (codePoint & 0xFFFFFFFFL);
    }
}
