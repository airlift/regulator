package io.airlift.regulator;

import io.airlift.regulator.Re2.ReplaceAllResult;
import io.airlift.regulator.TestingSpecializedPatternBenchmarkInputs.Operation;
import io.airlift.regulator.TestingSpecializedPatternBenchmarkInputs.Workload;
import io.airlift.regulator.TestingSpecializedPatternBenchmarks.Rotation;
import io.airlift.regulator.TestingSpecializedPatternBenchmarks.Variant;
import io.airlift.slice.Slice;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Param;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.Warmup;
import org.openjdk.jmh.runner.Runner;
import org.openjdk.jmh.runner.options.Options;

import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.TimeUnit;

import static io.airlift.regulator.Re2BenchmarkRunner.buildOptions;
import static io.airlift.regulator.TestingSpecializedPatternBenchmarks.constantCaller;
import static io.airlift.slice.Slices.EMPTY_SLICE;
import static io.airlift.slice.Slices.utf8Slice;
import static java.lang.invoke.MethodType.methodType;

/// Applies each specialized-pattern workload's operation through the public [Re2] API in the
/// three variants of [BenchmarkSpecializedTrinoRegexp]: the specialized engine, which interprets
/// the scan plan of the default compile; the regular engine, compiled without a scan plan; and
/// compiled, the plan's generated bytecode. `replace` is [Re2#replaceAll] and `extract` is
/// [Re2#extract], each with the rewrite `\N` of the workload's group, as native RE2's
/// `GlobalReplace` and `Extract` take it; `extractAll` reuses one [RegexpMatcher] and collects the
/// group of every match, as a native RE2 `Match` loop does. The compiled variant is const-bound
/// as the Trino one is: a per-pattern hidden class invokes the public call's handle, bound to the
/// generated-bytecode compile, as a class-data constant; extract-all also binds its matcher and
/// group when the handle is created and takes only the source when called. Only the `*Generated`
/// methods take the states that compile generated bytecode, so the forks of the other variants
/// load no generated class.
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(3)
@Warmup(iterations = 10, time = 1)
@Measurement(iterations = 5, time = 1)
public class BenchmarkSpecializedRe2
{
    @State(Scope.Thread)
    public static class ReplaceData
            extends WorkloadData
    {
        @Param("clickbenchHost")
        String workload;

        @Setup
        public void setup()
        {
            load(workload, Operation.REPLACE);
        }

        public void setWorkload(String workload)
        {
            this.workload = workload;
        }
    }

    @State(Scope.Thread)
    public static class ExtractData
            extends WorkloadData
    {
        @Param({"urlHostPort", "quotedField"})
        String workload;

        @Setup
        public void setup()
        {
            load(workload, Operation.EXTRACT);
        }

        public void setWorkload(String workload)
        {
            this.workload = workload;
        }
    }

    @State(Scope.Thread)
    public static class ExtractAllData
            extends WorkloadData
    {
        @Param({"queryParameterNames", "keyValue"})
        String workload;

        @Setup
        public void setup()
        {
            load(workload, Operation.EXTRACT_ALL);
        }

        public void setWorkload(String workload)
        {
            this.workload = workload;
        }
    }

    @State(Scope.Thread)
    public static class RegularEngineReplaceData
            extends RegularEngineData
    {
        @Setup
        public void setup(ReplaceData data)
        {
            load(data);
        }
    }

    @State(Scope.Thread)
    public static class RegularEngineExtractData
            extends RegularEngineData
    {
        @Setup
        public void setup(ExtractData data)
        {
            load(data);
        }
    }

    @State(Scope.Thread)
    public static class RegularEngineExtractAllData
            extends RegularEngineData
    {
        @Setup
        public void setup(ExtractAllData data)
        {
            load(data);
        }
    }

    @State(Scope.Thread)
    public static class GeneratedReplaceData
            extends GeneratedData
    {
        private ReplaceCaller generated;

        @Setup
        public void setup(ReplaceData data)
                throws ReflectiveOperationException
        {
            load(data);
            generated = constantCaller(ReplaceCaller.class, MethodHandles.lookup()
                    .findVirtual(Re2.class, "replaceAll", methodType(ReplaceAllResult.class, Slice.class, Slice.class))
                    .bindTo(re2));
        }
    }

    @State(Scope.Thread)
    public static class GeneratedExtractData
            extends GeneratedData
    {
        private ExtractCaller generated;

        @Setup
        public void setup(ExtractData data)
                throws ReflectiveOperationException
        {
            load(data);
            generated = constantCaller(ExtractCaller.class, MethodHandles.lookup()
                    .findVirtual(Re2.class, "extract", methodType(Slice.class, Slice.class, Slice.class))
                    .bindTo(re2));
        }
    }

    @State(Scope.Thread)
    public static class GeneratedExtractAllData
            extends GeneratedData
    {
        private ExtractAllCaller generated;

        @Setup
        public void setup(ExtractAllData data)
                throws ReflectiveOperationException
        {
            load(data);
            generated = constantCaller(ExtractAllCaller.class, MethodHandles.insertArguments(matcherExtractAllHandle().bindTo(matcher), 1, definition.group()));
        }
    }

    /// A workload's compile, with the rewrite of its group and a reusable matcher.
    abstract static class PatternData
            extends Rotation
    {
        Re2 re2;
        Slice rewrite;
        RegexpMatcher matcher;

        void load(Workload workload, Re2 re2)
        {
            rotate(workload);
            this.re2 = re2;
            int group = workload.capturedGroup();
            // A rewrite takes one digit after the backslash, so `\10` would name group 1 and a literal 0.
            if (workload.operation() != Operation.EXTRACT_ALL && group > 9) {
                throw new IllegalStateException("%s rewrite cannot name capture group %s".formatted(workload.workloadId(), group));
            }
            rewrite = utf8Slice("\\" + group);
            matcher = re2.matcher(EMPTY_SLICE);
        }
    }

    abstract static class WorkloadData
            extends PatternData
    {
        void load(String workloadId, Operation operation)
        {
            Workload workload = TestingSpecializedPatternBenchmarkInputs.create(workloadId);
            workload.requireOperation(operation);
            Re2 re2 = Re2.compile(workload.pattern());
            if (!re2.usesScanPlanForDiagnostics() || re2.usesGeneratedBytecode()) {
                throw new IllegalStateException("default compile does not interpret a scan plan: " + workloadId);
            }
            load(workload, re2);
        }
    }

    abstract static class RegularEngineData
            extends PatternData
    {
        void load(WorkloadData data)
        {
            Re2 regularEngine = Re2.compileWithoutScanPlanForTesting(data.definition.pattern(), Re2.Options.defaults());
            if (regularEngine.usesScanPlanForDiagnostics()) {
                throw new IllegalStateException("regular-engine compile has a scan plan: " + data.definition.workloadId());
            }
            load(data.definition, regularEngine);
        }
    }

    abstract static class GeneratedData
            extends PatternData
    {
        void load(WorkloadData data)
        {
            Re2 generated = Re2.compile(data.definition.pattern(), Re2.Options.defaults().setGenerateBytecode(true));
            if (!generated.usesGeneratedBytecode()) {
                throw new IllegalStateException("pattern has no generated bytecode: " + data.definition.workloadId());
            }
            load(data.definition, generated);
        }
    }

    interface ReplaceCaller
    {
        ReplaceAllResult replaceAll(Slice source, Slice rewrite);
    }

    interface ExtractCaller
    {
        Slice extract(Slice source, Slice rewrite);
    }

    interface ExtractAllCaller
    {
        List<Slice> extractAll(Slice source);
    }

    @Benchmark
    public ReplaceAllResult replace(ReplaceData data)
    {
        return data.re2.replaceAll(data.nextSource(), data.rewrite);
    }

    @Benchmark
    public ReplaceAllResult replaceRegularEngine(RegularEngineReplaceData data)
    {
        return data.re2.replaceAll(data.nextSource(), data.rewrite);
    }

    @Benchmark
    public ReplaceAllResult replaceGenerated(GeneratedReplaceData data)
    {
        return data.generated.replaceAll(data.nextSource(), data.rewrite);
    }

    @Benchmark
    public Slice extract(ExtractData data)
    {
        return data.re2.extract(data.nextSource(), data.rewrite);
    }

    @Benchmark
    public Slice extractRegularEngine(RegularEngineExtractData data)
    {
        return data.re2.extract(data.nextSource(), data.rewrite);
    }

    @Benchmark
    public Slice extractGenerated(GeneratedExtractData data)
    {
        return data.generated.extract(data.nextSource(), data.rewrite);
    }

    @Benchmark
    public List<Slice> extractAll(ExtractAllData data)
    {
        return matcherExtractAll(data.matcher, data.nextSource(), data.definition.group());
    }

    @Benchmark
    public List<Slice> extractAllRegularEngine(RegularEngineExtractAllData data)
    {
        return matcherExtractAll(data.matcher, data.nextSource(), data.definition.group());
    }

    @Benchmark
    public List<Slice> extractAllGenerated(GeneratedExtractAllData data)
    {
        return data.generated.extractAll(data.nextSource());
    }

    /// Returns `group` of every match in `source`, `null` where the group did not participate.
    static List<Slice> matcherExtractAll(RegexpMatcher matcher, Slice source, int group)
    {
        matcher.reset(source);
        List<Slice> values = new ArrayList<>();
        while (matcher.find()) {
            values.add(matcher.group(group));
        }
        return values;
    }

    /// [#matcherExtractAll] as a handle, to bind a matcher and group to.
    static MethodHandle matcherExtractAllHandle()
            throws ReflectiveOperationException
    {
        return MethodHandles.lookup().findStatic(BenchmarkSpecializedRe2.class, "matcherExtractAll", methodType(List.class, RegexpMatcher.class, Slice.class, int.class));
    }

    /// Sets up the states of `workloadId` as JMH does and returns its variants in the order
    /// specialized engine, regular engine, compiled, for tests and the native comparator's verifier.
    public static List<Variant> variantsForTesting(String workloadId)
            throws ReflectiveOperationException
    {
        BenchmarkSpecializedRe2 benchmark = new BenchmarkSpecializedRe2();
        return switch (TestingSpecializedPatternBenchmarkInputs.create(workloadId).operation()) {
            case REPLACE -> {
                ReplaceData data = new ReplaceData();
                data.setWorkload(workloadId);
                data.setup();
                RegularEngineReplaceData regularEngine = new RegularEngineReplaceData();
                regularEngine.setup(data);
                GeneratedReplaceData generated = new GeneratedReplaceData();
                generated.setup(data);
                yield List.of(
                        new Variant("specialized engine", data, () -> benchmark.replace(data)),
                        new Variant("regular engine", regularEngine, () -> benchmark.replaceRegularEngine(regularEngine)),
                        new Variant("compiled", generated, () -> benchmark.replaceGenerated(generated)));
            }
            case EXTRACT -> {
                ExtractData data = new ExtractData();
                data.setWorkload(workloadId);
                data.setup();
                RegularEngineExtractData regularEngine = new RegularEngineExtractData();
                regularEngine.setup(data);
                GeneratedExtractData generated = new GeneratedExtractData();
                generated.setup(data);
                yield List.of(
                        new Variant("specialized engine", data, () -> benchmark.extract(data)),
                        new Variant("regular engine", regularEngine, () -> benchmark.extractRegularEngine(regularEngine)),
                        new Variant("compiled", generated, () -> benchmark.extractGenerated(generated)));
            }
            case EXTRACT_ALL -> {
                ExtractAllData data = new ExtractAllData();
                data.setWorkload(workloadId);
                data.setup();
                RegularEngineExtractAllData regularEngine = new RegularEngineExtractAllData();
                regularEngine.setup(data);
                GeneratedExtractAllData generated = new GeneratedExtractAllData();
                generated.setup(data);
                yield List.of(
                        new Variant("specialized engine", data, () -> benchmark.extractAll(data)),
                        new Variant("regular engine", regularEngine, () -> benchmark.extractAllRegularEngine(regularEngine)),
                        new Variant("compiled", generated, () -> benchmark.extractAllGenerated(generated)));
            }
        };
    }

    public static void main(String[] args)
            throws Exception
    {
        Options options = buildOptions(BenchmarkSpecializedRe2.class, args);
        new Runner(options).run();
    }
}
