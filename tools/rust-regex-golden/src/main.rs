fn syntax_mode(cases: &[Vec<String>]) -> Result<Vec<String>, String> {
    let mut lines = vec![HEADER.to_string()];
    for case in cases {
        let (id, pattern_hex, options_field) = (&case[0], &case[1], &case[2]);
        let pattern = decode_utf8(pattern_hex, id)?;
        let options = Options::parse(options_field).map_err(|e| format!("{id}: {e}"))?;
        let compiled = compile(&pattern, options).map_err(|e| format!("{id}: {e}"))?;

        let mut fields = vec![
            ("id", Value::string(id)),
            ("patternHex", Value::string(pattern_hex)),
            ("options", Value::string(options_field)),
        ];
        match &compiled {
            Compiled::Accepted { public, .. } => {
                fields.push(("ok", Value::Bool(true)));
                push_error_fields(&mut fields, None)?;
                push_group_fields(&mut fields, public.captures_len(), &public.capture_names());
            }
            Compiled::Rejected { rejection, .. } => {
                fields.push(("ok", Value::Bool(false)));
                push_error_fields(&mut fields, Some(rejection))
                    .map_err(|e| format!("{id}: {e}"))?;
                fields.push(("groupCount", Value::Null));
                fields.push(("groupNames", Value::Null));
            }
        }
        lines.push(json_object(&fields));
    }
    Ok(lines)
}

fn match_mode(cases: &[Vec<String>]) -> Result<Vec<String>, String> {
    let mut lines = vec![HEADER.to_string()];
    for case in cases {
        let (id, pattern_hex, options_field, text_hex, start, end) =
            (&case[0], &case[1], &case[2], &case[3], &case[4], &case[5]);
        let pattern = decode_utf8(pattern_hex, id)?;
        let options = Options::parse(options_field).map_err(|e| format!("{id}: {e}"))?;
        let text = decode_text(text_hex, id, options)?;
        let window = parse_window(start, end, &text, options).map_err(|e| format!("{id}: {e}"))?;
        let compiled = compile(&pattern, options).map_err(|e| format!("{id}: {e}"))?;
        let windowed = window.is_some();
        let observed = match &compiled {
            Compiled::Accepted { .. } => {
                Some(observe(&compiled, &text, window).map_err(|e| format!("{id}: {e}"))?)
            }
            Compiled::Rejected { .. } => None,
        };

        let mut fields = vec![
            ("id", Value::string(id)),
            ("patternHex", Value::string(pattern_hex)),
            ("options", Value::string(options_field)),
            ("textHex", Value::string(text_hex)),
            ("start", Value::string(start)),
            ("end", Value::string(end)),
        ];
        result_fields(&mut fields, &compiled, observed.as_ref(), windowed)
            .map_err(|e| format!("{id}: {e}"))?;
        lines.push(json_object(&fields));
    }
    Ok(lines)
}

/// Parses a window: `-` and `-` mean no window. Otherwise the offsets must be
/// ordered and within the text, and in string mode on character boundaries; a
/// window of the bytes API may split a character.
fn parse_window(
    start: &str,
    end: &str,
    text: &[u8],
    options: Options,
) -> Result<Option<Range<usize>>, String> {
    match (start, end) {
        ("-", "-") => Ok(None),
        ("-", _) | (_, "-") => Err("start and end must both be - or both be offsets".to_string()),
        _ => {
            let start: usize = start
                .parse()
                .map_err(|_| format!("invalid start {start:?}"))?;
            let end: usize = end.parse().map_err(|_| format!("invalid end {end:?}"))?;
            if start > end || end > text.len() {
                return Err(format!(
                    "window {start}..{end} is not a range of the {}-byte text",
                    text.len()
                ));
            }
            if !options.bytes && (!is_char_boundary(text, start) || !is_char_boundary(text, end)) {
                return Err(format!(
                    "window {start}..{end} of a string search is not character-aligned"
                ));
            }
            Ok(Some(start..end))
        }
    }
}

/// Upstream cases a public `regex::Regex` string search can express. For the
/// bytes API the filter is the same except that it requires `utf8 = false`
/// and allows haystacks that are not UTF-8.
fn upstream_skip_reason(test: &RegexTest, bytes: bool) -> Option<&'static str> {
    if test.group() == REGEX_LITE_GROUP {
        return Some("regex-lite-only");
    }
    if test.regexes().len() != 1 {
        return Some("regex-set");
    }
    if test.match_kind() != regex_test::MatchKind::LeftmostFirst {
        return Some("match-kind");
    }
    if test.search_kind() != regex_test::SearchKind::Leftmost {
        return Some("search-kind");
    }
    if bytes && test.utf8() {
        return Some("utf8-enabled");
    }
    if !bytes && !test.utf8() {
        return Some("utf8-disabled");
    }
    if test.line_terminator() != LINE_TERMINATOR {
        return Some("line-terminator");
    }
    if !bytes && std::str::from_utf8(test.haystack()).is_err() {
        return Some("invalid-utf8-haystack");
    }
    None
}

/// What the upstream expectation is checked against.
#[derive(Clone)]
struct UpstreamObservation {
    build_error: Option<regex::Error>,
    is_match: bool,
    matches: Vec<Groups>,
}

fn upstream_mode(testdata: &Path, bytes: bool) -> Result<Vec<String>, String> {
    if std::env::var_os("REGEX_TEST").is_some() || std::env::var_os("REGEX_TEST_VERBOSE").is_some()
    {
        return Err("unset REGEX_TEST and REGEX_TEST_VERBOSE; they filter or redirect the regex-test runner".to_string());
    }

    let mut tests = RegexTests::new();
    for (group, path) in toml_files(testdata)? {
        let data =
            fs::read(&path).map_err(|e| format!("failed to read {}: {e}", path.display()))?;
        tests
            .load_slice(&group, &data)
            .map_err(|e| format!("failed to load {}: {e:#}", path.display()))?;
    }

    let mut skipped: BTreeMap<&'static str, usize> = BTreeMap::new();
    let mut kept = 0;
    let mut checked: Vec<RegexTest> = Vec::new();
    let mut observations: BTreeMap<String, UpstreamObservation> = BTreeMap::new();
    let mut records = Vec::new();
    for test in tests.iter() {
        if let Some(reason) = upstream_skip_reason(test, bytes) {
            *skipped.entry(reason).or_default() += 1;
            continue;
        }
        let id = format!("{}/{}", test.group(), test.name());
        let pattern = &test.regexes()[0];
        let text = test.haystack();
        let options = Options {
            case_insensitive: test.case_insensitive(),
            unicode_disabled: !test.unicode(),
            bytes,
            ..Options::default()
        };
        // Upstream bounds may split a character; the meta engine accepts any
        // byte range, and outside the bytes API its UTF-8 mode keeps matches
        // on character boundaries.
        let bounds = test.bounds();
        if bounds.start > bounds.end || bounds.end > text.len() {
            return Err(format!(
                "{id}: bounds {}..{} outside the {}-byte haystack",
                bounds.start,
                bounds.end,
                text.len()
            ));
        }
        let window =
            (bounds.start != 0 || bounds.end != text.len()).then_some(bounds.start..bounds.end);
        let windowed = window.is_some();
        let compiled = compile(pattern, options).map_err(|e| format!("{id}: {e}"))?;
        let mut anchored_iteration = false;
        let (observed, observation) = match &compiled {
            Compiled::Accepted { meta, .. } => {
                let range = window.clone().unwrap_or(0..text.len());
                let observed =
                    observe(&compiled, text, window.clone()).map_err(|e| format!("{id}: {e}"))?;
                let observation = if test.anchored() {
                    let matches = anchored_matches(meta, text, &range);
                    if matches.first() != observed.anchored.as_ref() {
                        return Err(format!("{id}: anchored iteration {matches:?} disagrees with the anchored search {:?}", observed.anchored));
                    }
                    // The fixture records only the first anchored match.
                    anchored_iteration = test.match_limit() != Some(1) && matches.len() > 1;
                    UpstreamObservation {
                        build_error: None,
                        is_match: observed.anchored.is_some(),
                        matches,
                    }
                } else {
                    UpstreamObservation {
                        build_error: None,
                        is_match: observed.search.is_match,
                        matches: observed.search.matches.clone(),
                    }
                };
                (Some(observed), observation)
            }
            Compiled::Rejected { public_error, .. } => (
                None,
                UpstreamObservation {
                    build_error: Some(public_error.clone()),
                    is_match: false,
                    matches: Vec::new(),
                },
            ),
        };

        if observations.insert(id.clone(), observation).is_some() {
            return Err(format!("duplicate upstream case {id}"));
        }
        checked.push(test.clone());
        if anchored_iteration {
            *skipped.entry("anchored-iteration").or_default() += 1;
            continue;
        }

        let (start, end) = match &window {
            Some(range) => (range.start.to_string(), range.end.to_string()),
            None => ("-".to_string(), "-".to_string()),
        };
        let mut fields = vec![
            ("id", Value::string(&id)),
            ("patternHex", Value::string(&encode_hex(pattern.as_bytes()))),
            ("options", Value::string(&options.render())),
            ("textHex", Value::string(&encode_hex(text))),
            ("start", Value::string(&start)),
            ("end", Value::string(&end)),
        ];
        result_fields(&mut fields, &compiled, observed.as_ref(), windowed)
            .map_err(|e| format!("{id}: {e}"))?;
        records.push(json_object(&fields));
        kept += 1;
    }

    // Every test that passes the static filters is checked, including anchored
    // tests left out of the fixture because they iterate.
    check_upstream_expectations(&checked, &observations)?;

    let skipped_total: usize = skipped.values().sum();
    let summary = skipped
        .iter()
        .map(|(reason, count)| format!("{reason}={count}"))
        .collect::<Vec<_>>()
        .join(" ");
    eprintln!(
        "{}: kept {kept} cases, skipped {skipped_total}, checked {}: {summary}",
        if bytes { "upstream-bytes" } else { "upstream" },
        checked.len()
    );
    let mut lines = vec![
        HEADER.to_string(),
        format!("# kept={kept} skipped={skipped_total} {summary}"),
    ];
    lines.extend(records);
    Ok(lines)
}

/// Checks every kept case against its TOML expectation with the regex-test
/// runner, expanded into the same is_match, find, and captures checks the
/// regex crate's own string and bytes suites run. Any failure aborts
/// generation.
fn check_upstream_expectations(
    checked: &[RegexTest],
    observations: &BTreeMap<String, UpstreamObservation>,
) -> Result<(), String> {
    let mut runner =
        TestRunner::new().map_err(|e| format!("failed to create the regex-test runner: {e:#}"))?;
    runner
        .expand(&["is_match", "find", "captures"], |test| test.compiles())
        .test_iter(checked.iter(), |test, _| {
            let id = format!("{}/{}", test.group(), test.name());
            let observation = observations[&id].clone();
            if let Some(error) = observation.build_error {
                return Err(error.into());
            }
            Ok(CompiledRegex::compiled(move |test| {
                expected_result(&observation, test)
            }))
        })
        .assert();
    Ok(())
}

fn expected_result(observation: &UpstreamObservation, test: &RegexTest) -> TestResult {
    let limit = test.match_limit().unwrap_or(usize::MAX);
    let span = |(start, end): (usize, usize)| regex_test::Span { start, end };
    match test.additional_name() {
        "is_match" => TestResult::matched(observation.is_match),
        "find" => TestResult::matches(observation.matches.iter().take(limit).map(|groups| {
            regex_test::Match {
                id: 0,
                span: span(groups[0].expect("group zero participates in every match")),
            }
        })),
        "captures" => TestResult::captures(observation.matches.iter().take(limit).map(|groups| {
            regex_test::Captures::new(0, groups.iter().map(|group| group.map(span)))
                .expect("group zero participates in every match")
        })),
        name => TestResult::fail(&format!("unrecognized test name: {name}")),
    }
}

/// Every TOML file under the test data directory, named by its path relative
/// to that directory without the extension, as the regex crate's suite names
/// them.
fn toml_files(testdata: &Path) -> Result<Vec<(String, std::path::PathBuf)>, String> {
    let mut files = BTreeSet::new();
    let mut directories = vec![testdata.to_path_buf()];
    while let Some(directory) = directories.pop() {
        let entries = fs::read_dir(&directory)
            .map_err(|e| format!("failed to list {}: {e}", directory.display()))?;
        for entry in entries {
            let path = entry
                .map_err(|e| format!("failed to list {}: {e}", directory.display()))?
                .path();
            if path.is_dir() {
                directories.push(path);
            } else if path.extension().and_then(|extension| extension.to_str()) == Some("toml") {
                files.insert(path);
            }
        }
    }
    if files.is_empty() {
        return Err(format!("no TOML files under {}", testdata.display()));
    }
    files
        .into_iter()
        .map(|path| {
            let relative = path
                .strip_prefix(testdata)
                .expect("listed under testdata")
                .with_extension("");
            let group = relative
                .to_str()
                .ok_or_else(|| format!("non-UTF-8 path {}", path.display()))?
                .replace(std::path::MAIN_SEPARATOR, "/");
            Ok((group, path))
        })
        .collect()
}

