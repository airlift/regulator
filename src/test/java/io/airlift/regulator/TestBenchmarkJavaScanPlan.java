package io.airlift.regulator;

import io.airlift.slice.Slice;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

public class TestBenchmarkJavaScanPlan
{
    @Test
    public void testBenchmarkResults()
            throws ReflectiveOperationException
    {
        assertThat(BenchmarkJavaScanPlan.workloads()).isEqualTo(BenchmarkRe2ScanPlan.workloads());
        BenchmarkJavaScanPlan benchmark = new BenchmarkJavaScanPlan();
        for (String workload : BenchmarkJavaScanPlan.workloads()) {
            for (boolean dotAll : new boolean[] {true, false}) {
                for (boolean javaDollar : new boolean[] {true, false}) {
                    for (boolean javaLineTerminators : new boolean[] {true, false}) {
                        // With dotAll, javaLineTerminators changes nothing.
                        if (dotAll && javaLineTerminators) {
                            continue;
                        }
                        // Generated bytecode needs a plan, so it is requested only with scanPlan=true.
                        for (Variant variant : List.of(new Variant(true, false), new Variant(false, false), new Variant(true, true))) {
                            boolean scanPlan = variant.scanPlan();
                            boolean generateBytecode = variant.generateBytecode();
                            String state = "%s dotAll=%s scanPlan=%s generateBytecode=%s javaDollar=%s javaLineTerminators=%s".formatted(workload, dotAll, scanPlan, generateBytecode, javaDollar, javaLineTerminators);
                            // Each method advances its own cursor, so give each one a separate state.
                            BenchmarkJavaScanPlan.BenchmarkData contains = data(workload, dotAll, javaDollar, javaLineTerminators, variant);
                            BenchmarkJavaScanPlan.BenchmarkData count = data(workload, dotAll, javaDollar, javaLineTerminators, variant);
                            BenchmarkJavaScanPlan.BenchmarkData boundaries = data(workload, dotAll, javaDollar, javaLineTerminators, variant);
                            BenchmarkJavaScanPlan.BenchmarkData extract = data(workload, dotAll, javaDollar, javaLineTerminators, variant);
                            BenchmarkJavaScanPlan.BenchmarkData extractAll = data(workload, dotAll, javaDollar, javaLineTerminators, variant);
                            BenchmarkJavaScanPlan.BenchmarkData compile = data(workload, dotAll, javaDollar, javaLineTerminators, variant);
                            // The rows are the RE2 benchmark's, and each Java pattern matches what its
                            // RE2 pattern matches, or what the ordinary engine matches with
                            // javaDollar=true, since some rows hold a line terminator, and with
                            // javaLineTerminators=true, since on the malformed rows the default dot
                            // rejects some sequences that RE2's dot accepts. With scanPlan=true, each
                            // Java pattern selects a plan, and a generated class when
                            // generateBytecode=true, exactly when its RE2 pattern does, with Java's $
                            // and default dot too; with scanPlan=false, it selects neither.
                            BenchmarkRe2ScanPlan.BenchmarkData re2 = re2Data(workload, dotAll, generateBytecode);
                            assertThat(contains.inputs).as(state).isEqualTo(re2.inputs);
                            for (int index = 0; index < contains.patterns.length; index++) {
                                String re2Expression = re2.expressions[index].toStringUtf8();
                                assertThat(contains.patterns[index].re2().usesScanPlanForDiagnostics())
                                        .as("%s pattern %s", state, index)
                                        .isEqualTo(scanPlan && re2.patterns[index].usesScanPlanForDiagnostics());
                                assertThat(contains.patterns[index].usesGeneratedBytecode())
                                        .as("%s pattern %s", state, index)
                                        .isEqualTo(scanPlan && re2.patterns[index].usesGeneratedBytecode());
                                assertThat(contains.expressions[index].toStringUtf8().contains("$"))
                                        .as("%s pattern %s", state, index)
                                        .isEqualTo(javaDollar && re2Expression.contains("$"));
                                assertThat(contains.expressions[index].toStringUtf8().startsWith("(?d)"))
                                        .as("%s pattern %s", state, index)
                                        .isEqualTo(!dotAll && !javaLineTerminators);
                            }
                            JavaRegexp[] patterns = Arrays.stream(contains.expressions).map(JavaRegexp::compile).toArray(JavaRegexp[]::new);
                            JavaRegexp[] ordinary = Arrays.stream(contains.expressions)
                                    .map(expression -> JavaRegexp.compileWithoutScanPlanForTesting(expression, JavaRegexp.Options.defaults()))
                                    .toArray(JavaRegexp[]::new);
                            boolean[] planMatched = new boolean[patterns.length];
                            // Continue past the last row so that each method's cursor also wraps around.
                            for (int call = 0; call < contains.inputs.length + patterns.length + 1; call++) {
                                int row = call % contains.inputs.length;
                                int patternIndex = row % patterns.length;
                                Slice input = contains.inputs[row];
                                JavaRegexp pattern = patterns[patternIndex];
                                int group = pattern.capturingGroupCount() == 0 ? 0 : 1;
                                String description = state + " row=" + row;

                                MatchResult match = pattern.findResult(input);
                                MatchResult expected = javaDollar || javaLineTerminators ? ordinary[patternIndex].findResult(input) : re2.patterns[patternIndex].findResult(input);
                                assertThat(groupBounds(match)).as(description).isEqualTo(groupBounds(expected));
                                planMatched[patternIndex] |= match != null;
                                assertThat(benchmark.contains(contains)).as(description).isEqualTo(match != null);
                                assertThat(benchmark.count(count)).as(description).isEqualTo(pattern.count(input));
                                long expectedBoundaries = match == null ? -1 : ((long) match.start() << 32) | match.end();
                                assertThat(benchmark.boundaries(boundaries)).as(description).isEqualTo(expectedBoundaries);
                                assertThat(benchmark.extract(extract)).as(description).isEqualTo(match == null ? null : match.groupSlice(group));

                                RegexpMatcher matcher = pattern.matcher(input);
                                List<Slice> expectedMatches = new ArrayList<>();
                                while (matcher.find()) {
                                    expectedMatches.add(matcher.group(group));
                                }
                                assertThat(benchmark.extractAll(extractAll)).as(description).isEqualTo(expectedMatches);

                                // Each compile with generated bytecode defines a class, so one pass over the plans suffices.
                                if (!generateBytecode || call < patterns.length) {
                                    JavaRegexp compiled = benchmark.compile(compile);
                                    assertThat(compiled.capturingGroupCount()).as(description).isEqualTo(pattern.capturingGroupCount());
                                    assertThat(compiled.find(input)).as(description).isEqualTo(match != null);
                                    assertThat(compiled.re2().usesScanPlanForDiagnostics()).as(description)
                                            .isEqualTo(contains.patterns[patternIndex].re2().usesScanPlanForDiagnostics());
                                    assertThat(compiled.usesGeneratedBytecode()).as(description).isEqualTo(contains.patterns[patternIndex].usesGeneratedBytecode());
                                }
                            }
                            // A row paired with the wrong plan would time only failure paths.
                            assertThat(planMatched).as(state).containsOnly(true);
                        }
                    }
                }
            }
        }
    }

    private static List<Integer> groupBounds(MatchResult match)
    {
        if (match == null) {
            return null;
        }
        List<Integer> bounds = new ArrayList<>();
        for (int group = 0; group <= match.groupCount(); group++) {
            bounds.add(match.start(group));
            bounds.add(match.end(group));
        }
        return bounds;
    }

    private record Variant(boolean scanPlan, boolean generateBytecode) {}

    private static BenchmarkJavaScanPlan.BenchmarkData data(String workload, boolean dotAll, boolean javaDollar, boolean javaLineTerminators, Variant variant)
    {
        BenchmarkJavaScanPlan.BenchmarkData data = new BenchmarkJavaScanPlan.BenchmarkData();
        data.workload = workload;
        data.dotAll = dotAll;
        data.scanPlan = variant.scanPlan();
        data.generateBytecode = variant.generateBytecode();
        data.javaDollar = javaDollar;
        data.javaLineTerminators = javaLineTerminators;
        data.setup();
        return data;
    }

    private static BenchmarkRe2ScanPlan.BenchmarkData re2Data(String workload, boolean dotAll, boolean generateBytecode)
    {
        BenchmarkRe2ScanPlan.BenchmarkData data = new BenchmarkRe2ScanPlan.BenchmarkData();
        data.workload = workload;
        data.dotAll = dotAll;
        data.scanPlan = true;
        data.generateBytecode = generateBytecode;
        data.setup();
        return data;
    }
}
