package io.airlift.regulator;

import org.junit.jupiter.api.Test;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

public class TestOptionalTrinoScanKernel
{
    /**
     * Patterns compiled without generated bytecode run every operation without loading the
     * generated-code subclasses, the generator, the helper copies, or the classfile library.
     */
    @Test
    public void testDisabledGenerationLoadsNoGeneratedCode()
            throws Exception
    {
        Path classLoadLog = Files.createTempFile("trino-scan-kernel-class-load-", ".log");
        try {
            List<String> command = new ArrayList<>();
            command.add(System.getProperty("java.home") + "/bin/java");
            command.add("-Xlog:class+load=info:file=" + classLoadLog);
            command.add("--add-modules");
            command.add("jdk.incubator.vector");
            command.add("-cp");
            command.add(System.getProperty("java.class.path"));
            command.add(TrinoScanKernelProbe.class.getName());

            ProcessBuilder processBuilder = new ProcessBuilder(command)
                    .redirectErrorStream(true);
            processBuilder.environment().remove("JDK_JAVA_OPTIONS");
            Process process = processBuilder.start();
            String output = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
            int exitCode = process.waitFor();
            assertThat(exitCode).as(output).isZero();
            assertThat(output).contains("OK");
            assertThat(Files.readString(classLoadLog))
                    .contains("io.airlift.regulator.TrinoScanPlan source:")
                    .contains("io.airlift.regulator.VectorTrinoScanner source:")
                    .doesNotContain("io.airlift.regulator.TrinoRegexp$CompiledScanTrinoRegexp ")
                    .doesNotContain("io.airlift.regulator.TrinoRegexpMatcher$CompiledScanMatcher ")
                    .doesNotContain("io.airlift.regulator.TrinoScanKernelGenerator")
                    .doesNotContain("io.airlift.regulator.TrinoScanKernelSupport ")
                    .doesNotContain("io.airlift.regulator.VectorTrinoScanKernelSupport ")
                    .doesNotContain("CompiledTrinoScan")
                    .doesNotContain("io.airlift.classfile.");
        }
        finally {
            Files.deleteIfExists(classLoadLog);
        }
    }
}
