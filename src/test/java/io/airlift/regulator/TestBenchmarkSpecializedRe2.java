package io.airlift.regulator;

import io.airlift.regulator.BenchmarkSpecializedRe2.PatternData;
import io.airlift.regulator.Re2.ReplaceAllResult;
import io.airlift.regulator.TestingEverydayTrinoRegexpBenchmarkInputs.Source;
import io.airlift.regulator.TestingSpecializedPatternBenchmarkInputs.Operation;
import io.airlift.regulator.TestingSpecializedPatternBenchmarkInputs.Workload;
import io.airlift.regulator.TestingSpecializedPatternBenchmarks.Variant;
import org.junit.jupiter.api.Test;
import org.openjdk.jmh.annotations.Param;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;

import static io.airlift.regulator.TestRe2ScanPlan.disableInterpretedPlan;
import static io.airlift.regulator.TestScanPlan.disableOrdinaryEngine;
import static io.airlift.slice.Slices.utf8Slice;
import static org.assertj.core.api.Assertions.assertThat;

public class TestBenchmarkSpecializedRe2
{
    private static final Path CATALOG = Path.of("tools/re2-benchmark/baseline/specialized-patterns.tsv");
    // One matching source of each workload and its result there; the replace pattern spans the
    // whole URL, so replacing it with the host group leaves only the host.
    private static final Map<String, Capture> CAPTURES = Map.of(
            "clickbenchHost", new Capture("www-query", new ReplaceAllResult(1, utf8Slice("example.com"))),
            "urlHostPort", new Capture("port-asset", utf8Slice("cdn.example.net")),
            "queryParameterNames", new Capture("query-three", List.of(utf8Slice("q"), utf8Slice("lang"), utf8Slice("page"))),
            "keyValue", new Capture("three-pairs", List.of(utf8Slice("7"), utf8Slice("ready"), utf8Slice("2"))),
            "quotedField", new Capture("prefixed", utf8Slice("request complete")));

    @Test
    public void testWorkloads()
            throws ReflectiveOperationException
    {
        assertThat(parameters(BenchmarkSpecializedRe2.ReplaceData.class)).containsExactlyElementsOf(TestingSpecializedPatternBenchmarkInputs.workloadIds(Operation.REPLACE));
        assertThat(parameters(BenchmarkSpecializedRe2.ExtractData.class)).containsExactlyElementsOf(TestingSpecializedPatternBenchmarkInputs.workloadIds(Operation.EXTRACT));
        assertThat(parameters(BenchmarkSpecializedRe2.ExtractAllData.class)).containsExactlyElementsOf(TestingSpecializedPatternBenchmarkInputs.workloadIds(Operation.EXTRACT_ALL));
    }

    @Test
    public void testCatalogDescribesTheWorkloads()
            throws Exception
    {
        // The baseline's rows.tsv and the report take the workloads from this catalog.
        List<String> catalog = Files.readAllLines(CATALOG).stream()
                .filter(line -> line.startsWith("re2-specialized-patterns-"))
                .map(line -> String.join("\t", List.of(line.split("\t", -1)).subList(1, 4)))
                .toList();
        assertThat(catalog).containsExactlyElementsOf(TestingSpecializedPatternBenchmarkInputs.workloadIds().stream()
                .map(TestingSpecializedPatternBenchmarkInputs::create)
                .map(workload -> String.join("\t", workload.workloadId(), workload.operation().benchmarkName(), workload.pattern().toStringUtf8()))
                .toList());
    }

    @Test
    public void testEveryVariantProducesTheSameResult()
            throws ReflectiveOperationException
    {
        for (String workloadId : TestingSpecializedPatternBenchmarkInputs.workloadIds()) {
            Workload workload = TestingSpecializedPatternBenchmarkInputs.create(workloadId);
            List<Variant> variants = BenchmarkSpecializedRe2.variantsForTesting(workloadId);
            List<Source> sources = workload.sources();
            List<Object> expected = expectedResults(workload, variants.get(1));
            Capture capture = CAPTURES.get(workloadId);
            int captureIndex = sources.stream().map(Source::sourceId).toList().indexOf(capture.sourceId());
            assertThat(expected.get(captureIndex)).as("%s/%s", workloadId, capture.sourceId()).isEqualTo(capture.result());

            // With the ordinary engine matching nothing, only the scan plan can return the specialized
            // engine's results; with the interpreted plan removed as well, only generated bytecode can
            // return the compiled variant's.
            Re2 specialized = ((PatternData) variants.get(0).state()).re2;
            Re2 compiled = ((PatternData) variants.get(2).state()).re2;
            disableOrdinaryEngine(specialized);
            disableOrdinaryEngine(compiled);
            disableInterpretedPlan(compiled);

            // Started at the first source, each variant returns each source's result as its
            // rotation advances and wraps around.
            for (Variant variant : variants) {
                variant.setSourceIndex(0);
                for (int call = 0; call <= sources.size(); call++) {
                    int sourceIndex = call % sources.size();
                    assertThat(variant.invoke()).as("%s/%s %s", workloadId, sources.get(sourceIndex).sourceId(), variant.name()).isEqualTo(expected.get(sourceIndex));
                }
            }
        }

        // The native gate compares results as the runners print them: the value count, then each
        // value in hex, or `-` for a group that did not participate.
        assertThat(SpecializedPatternNativeInputs.values(Arrays.asList(utf8Slice("q"), null))).isEqualTo("2:71,-");
    }

    /// The regular engine's result for each source, checked against the source's expected match count.
    private static List<Object> expectedResults(Workload workload, Variant regularEngine)
    {
        List<Object> expected = new ArrayList<>();
        for (int sourceIndex = 0; sourceIndex < workload.sources().size(); sourceIndex++) {
            Source source = workload.sources().get(sourceIndex);
            String description = workload.workloadId() + "/" + source.sourceId();
            Object result = regularEngine.invoke(sourceIndex);
            long matches = source.expectedMatchCount();
            switch (workload.operation()) {
                case REPLACE -> assertThat(((ReplaceAllResult) result).replacementCount()).as(description).isEqualTo(matches);
                case EXTRACT -> assertThat(result == null).as(description).isEqualTo(matches == 0);
                case EXTRACT_ALL -> assertThat((List<?>) result).as(description).hasSize((int) matches);
            }
            expected.add(result);
        }
        return expected;
    }

    private static List<String> parameters(Class<?> state)
            throws ReflectiveOperationException
    {
        return List.of(state.getDeclaredField("workload").getAnnotation(Param.class).value());
    }

    private record Capture(String sourceId, Object result) {}
}
