package io.airlift.regulator;

import io.airlift.slice.Slice;

import java.util.Arrays;

import static io.airlift.slice.Slices.utf8Slice;
import static java.nio.charset.StandardCharsets.UTF_8;

public final class VectorScannerProbe
{
    private static final String FILLER = "y".repeat(64);

    private VectorScannerProbe() {}

    public static void main(String[] arguments)
    {
        boolean expectedVectorScans = Boolean.parseBoolean(arguments[0]);
        check(VectorSupport.isAvailable() == expectedVectorScans, "unexpected vector scanner availability");

        // Each pattern is a scan plan, and its text is longer than the 128-bit vector scans.
        // Anchored runs of one-byte sets stop with the run scan.
        verify("^abc(?:(x+))?y*$",
                "LITERAL,FORK,SAVE,RUN,SAVE,RUN,END",
                null,
                false,
                "abc" + "x".repeat(64) + FILLER,
                "x".repeat(64),
                1);
        verify("^([^/]{2,})/$",
                "RUN,LITERAL,END",
                null,
                false,
                "h".repeat(64) + "/",
                "h".repeat(64),
                1);
        // A literal-leading unanchored search finds its first byte.
        verify("https?://([^/]+)/",
                "LITERAL,OPTIONAL,LITERAL,SAVE,RUN,SAVE,LITERAL",
                null,
                false,
                FILLER + "https://" + "h".repeat(64) + "/" + FILLER,
                "h".repeat(64),
                1);
        // A complement run's candidate scan skips its one non-member byte.
        verify("([^/]+)/",
                "SAVE,RUN,SAVE,LITERAL",
                "/",
                false,
                "/".repeat(64) + "host/",
                "host",
                1);
        // The byte-set candidate scans: a small set, a range, and a nibble table.
        verify("[?&]([^=]+)=",
                "RUN,SAVE,RUN,SAVE,LITERAL",
                "=",
                false,
                FILLER + "?key=" + FILLER + "&other=",
                "key",
                2);
        verify("[a-e](\\d+)",
                "RUN,SAVE,RUN,SAVE",
                null,
                false,
                "x".repeat(64) + "c12" + "x".repeat(64),
                "12",
                1);
        // Each member's low nibble is in the upper half of the 16-entry nibble table.
        verify("[hxyz](\\d+)",
                "RUN,SAVE,RUN,SAVE",
                null,
                false,
                "-".repeat(64) + "z12" + "-".repeat(64),
                "12",
                1);
        // After the first failed attempt, a run-leading search checks for its required literal.
        verify("([^:]+):([0-9]+)",
                "SAVE,RUN,SAVE,LITERAL,SAVE,RUN,SAVE",
                ":",
                false,
                "abc:x" + FILLER + ":12",
                "x" + FILLER,
                1);
        verify("([^:]+):([0-9]+)",
                "SAVE,RUN,SAVE,LITERAL,SAVE,RUN,SAVE",
                ":",
                false,
                "abc:x" + FILLER,
                null,
                0);
        // The ASCII-folded executor finds a folded leading letter in either case.
        verify("(?i)content-type:([^;]+);",
                "ASCII_FOLDED_LITERAL,SAVE,RUN,SAVE,LITERAL",
                null,
                true,
                FILLER + "CONTENT-TYPE:text;" + FILLER + "content-type:html;",
                "text",
                2);

        // The DFA's mixed start-byte scan uses the same nibble-table lookup for texts of at least 1 KiB.
        // A boolean find runs on the forward longest-match DFA.
        Re2 mixedSet = Re2.compile(utf8Slice("[hxyz]\\d{3}"));
        check(mixedSet.find(utf8Slice("-".repeat(2000) + "x123" + "-".repeat(10))), "[hxyz]\\d{3}: find failed");
        Dfa.DfaInstance mixedSetDfa = mixedSet.forwardProgramForDiagnostics().getCachedDfa(Dfa.DfaInstance.Kind.LONGEST_MATCH);
        check((mixedSetDfa.mixedByteSetScanCount() > 0) == expectedVectorScans, "[hxyz]\\d{3}: unexpected mixed byte set strategy");

        // A generated scan-plan kernel scans for its run's candidates with the same nibble-table lookup.
        TrinoRegexp generated = TrinoRegexp.compile(utf8Slice("[hxyz](\\d+)"), TrinoRegexp.Options.defaults().setGenerateBytecode(true));
        check(generated.usesGeneratedBytecode(), "[hxyz](\\d+): no generated bytecode");
        check(utf8Slice("12").equals(generated.extract(utf8Slice("-".repeat(64) + "z12" + "-".repeat(64)), 1)), "[hxyz](\\d+): generated extract failed");

        // A literal alternation skips to its start literal filter's candidates only with the
        // Vector API; without it, the trie's root table reads every byte.
        TrinoRegexp alternation = TrinoRegexp.compile(utf8Slice("Sherlock Holmes|John Watson|Irene Adler"));
        check(alternation.literalAlternationSpanMatcher().usesStartLiteralFilter(FILLER.length()) == expectedVectorScans, "literal alternation: unexpected route");
        check(alternation.count(utf8Slice(FILLER + "John Watson" + FILLER + "Irene Adler")) == 2, "literal alternation: count failed");
        // The start literal filter looks up each candidate's first byte by its low nibble, here
        // 8 to 10, and the search stops at the filter's candidates only with the Vector API.
        TrinoRegexp nibbleAlternation = TrinoRegexp.compile(utf8Slice("xray|yoke|zinc|hymn"));
        check(nibbleAlternation.contains(utf8Slice("-".repeat(100) + "zinc" + "-".repeat(10))), "xray|yoke|zinc|hymn: find failed");
        check((nibbleAlternation.literalAlternationSpanMatcher().filterStopCountForDiagnostics() > 0) == expectedVectorScans, "xray|yoke|zinc|hymn: unexpected route");

        System.out.printf("OK %s%n", expectedVectorScans ? "vector" : "scalar");
    }

    private static void verify(String expression, String operations, String requiredLiteral, boolean asciiFolded, String text, String group, int count)
    {
        TrinoRegexp regexp = TrinoRegexp.compile(utf8Slice(expression));
        check(regexp.re2().usesScanPlanForDiagnostics(), expression + ": no scan plan");
        check(regexp.re2().usesAsciiFoldedScanExecutorForDiagnostics() == asciiFolded, expression + ": unexpected executor");
        ParseResult parsed = TrinoRegexpParser.parse(utf8Slice(expression), Regexp.LIKE_PERL);
        ScanPlan plan = ScanPlan.analyze(parsed.regexp(), parsed.capturingGroupCount(), ScanPlan.Language.TRINO, false, parsed.caseFolding(), ByteFrequencies.uniform());
        check(plan != null, expression + ": no plan");
        check(plan.operationsForDiagnostics().equals(operations), expression + ": unexpected operations " + plan.operationsForDiagnostics());
        byte[] required = plan.requiredLiteralForDiagnostics();
        check(requiredLiteral == null ? required == null : Arrays.equals(required, requiredLiteral.getBytes(UTF_8)), expression + ": unexpected required literal");

        Slice source = utf8Slice(text);
        check(regexp.contains(source) == (group != null), expression + ": contains failed");
        Slice extracted = regexp.extract(source, 1);
        check(group == null ? extracted == null : extracted != null && extracted.equals(utf8Slice(group)), expression + ": extract failed");
        check(regexp.count(source) == count, expression + ": count failed");
    }

    private static void check(boolean condition, String message)
    {
        if (!condition) {
            throw new AssertionError(message);
        }
    }
}
