package io.airlift.regulator;

import io.airlift.slice.Slice;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;

import static io.airlift.slice.Slices.utf8Slice;
import static org.assertj.core.api.Assertions.assertThat;

public class TestBenchmarkRustScanPlan
{
    @Test
    public void testBenchmarkResults()
            throws ReflectiveOperationException
    {
        assertThat(BenchmarkRustScanPlan.workloads()).isEqualTo(BenchmarkRe2ScanPlan.workloads());
        BenchmarkRustScanPlan benchmark = new BenchmarkRustScanPlan();
        for (String workload : BenchmarkRustScanPlan.workloads()) {
            for (boolean dotAll : new boolean[] {true, false}) {
                for (boolean unicodePerlClasses : new boolean[] {true, false}) {
                    // Generated bytecode needs a plan, so it is requested only with scanPlan=true.
                    for (Variant variant : List.of(new Variant(true, false), new Variant(false, false), new Variant(true, true))) {
                        boolean scanPlan = variant.scanPlan();
                        boolean generateBytecode = variant.generateBytecode();
                        String state = "%s dotAll=%s scanPlan=%s generateBytecode=%s unicodePerlClasses=%s".formatted(workload, dotAll, scanPlan, generateBytecode, unicodePerlClasses);
                        // Each method advances its own cursor, so give each one a separate state.
                        BenchmarkRustScanPlan.BenchmarkData contains = data(workload, dotAll, unicodePerlClasses, variant);
                        BenchmarkRustScanPlan.BenchmarkData count = data(workload, dotAll, unicodePerlClasses, variant);
                        BenchmarkRustScanPlan.BenchmarkData boundaries = data(workload, dotAll, unicodePerlClasses, variant);
                        BenchmarkRustScanPlan.BenchmarkData extract = data(workload, dotAll, unicodePerlClasses, variant);
                        BenchmarkRustScanPlan.BenchmarkData extractAll = data(workload, dotAll, unicodePerlClasses, variant);
                        BenchmarkRustScanPlan.BenchmarkData compile = data(workload, dotAll, unicodePerlClasses, variant);
                        // The rows are the RE2 benchmark's, and each Rust pattern matches what its RE2
                        // pattern matches, or with unicodePerlClasses=true what the ordinary engine
                        // matches. Outside byte mode, results on malformed UTF-8 are unspecified;
                        // with ASCII Perl classes the RE2 result stands for Regulator's ordinary
                        // engine on the malformed rows, since that engine decodes malformed input by
                        // RE2's rules. With scanPlan=true, each Rust pattern selects a plan, and a
                        // generated class when generateBytecode=true, exactly when its RE2 pattern
                        // does, Unicode Perl classes included; with scanPlan=false, it selects
                        // neither.
                        BenchmarkRe2ScanPlan.BenchmarkData re2 = re2Data(workload, dotAll, generateBytecode);
                        assertThat(contains.inputs).as(state).isEqualTo(re2.inputs);
                        boolean[] unicodeClasses = new boolean[contains.patterns.length];
                        for (int index = 0; index < contains.patterns.length; index++) {
                            String re2Expression = re2.expressions[index].toStringUtf8();
                            boolean perlClass = re2Expression.contains("\\d") || re2Expression.contains("\\w");
                            unicodeClasses[index] = unicodePerlClasses && perlClass;
                            assertThat(contains.patterns[index].pattern().usesScanPlanForDiagnostics())
                                    .as("%s pattern %s", state, index)
                                    .isEqualTo(scanPlan && re2.patterns[index].usesScanPlanForDiagnostics());
                            assertThat(contains.patterns[index].usesGeneratedBytecode())
                                    .as("%s pattern %s", state, index)
                                    .isEqualTo(scanPlan && re2.patterns[index].usesGeneratedBytecode());
                            assertThat(contains.expressions[index].toStringUtf8().contains("(?-u:"))
                                    .as("%s pattern %s", state, index)
                                    .isEqualTo(!unicodePerlClasses && perlClass);
                        }
                        RustRegexp[] patterns = Arrays.stream(contains.expressions).map(RustRegexp::compile).toArray(RustRegexp[]::new);
                        RustRegexp[] ordinary = Arrays.stream(contains.expressions)
                                .map(expression -> RustRegexp.compileWithoutScanPlanForTesting(expression, RustRegexp.Options.defaults()))
                                .toArray(RustRegexp[]::new);
                        boolean[] planMatched = new boolean[patterns.length];
                        boolean[] unicodeDiffered = new boolean[patterns.length];
                        boolean[][] nonAsciiCaptureDiffered = new boolean[patterns.length][];
                        for (int index = 0; index < patterns.length; index++) {
                            nonAsciiCaptureDiffered[index] = new boolean[patterns[index].capturingGroupCount()];
                        }
                        // Continue past the last row so that each method's cursor also wraps around.
                        for (int call = 0; call < contains.inputs.length + patterns.length + 1; call++) {
                            int row = call % contains.inputs.length;
                            int patternIndex = row % patterns.length;
                            Slice input = contains.inputs[row];
                            RustRegexp pattern = patterns[patternIndex];
                            int group = pattern.capturingGroupCount() == 0 ? 0 : 1;
                            String description = state + " row=" + row;

                            MatchResult match = pattern.findResult(input);
                            MatchResult re2Match = re2.patterns[patternIndex].findResult(input);
                            MatchResult expected = unicodePerlClasses ? ordinary[patternIndex].findResult(input) : re2Match;
                            assertThat(groupBounds(match)).as(description).isEqualTo(groupBounds(expected));
                            if (!Objects.equals(groupBounds(match), groupBounds(re2Match))) {
                                unicodeDiffered[patternIndex] = true;
                                for (int captureGroup = 1; match != null && captureGroup <= match.groupCount(); captureGroup++) {
                                    Slice captured = match.groupSlice(captureGroup);
                                    nonAsciiCaptureDiffered[patternIndex][captureGroup - 1] |= captured != null && !captured.toStringUtf8().chars().allMatch(character -> character < 0x80);
                                }
                            }
                            planMatched[patternIndex] |= match != null;
                            assertThat(benchmark.contains(contains)).as(description).isEqualTo(match != null);
                            assertThat(benchmark.count(count)).as(description).isEqualTo(pattern.count(input));
                            long expectedBoundaries = match == null ? -1 : ((long) match.start() << 32) | match.end();
                            assertThat(benchmark.boundaries(boundaries)).as(description).isEqualTo(expectedBoundaries);
                            assertThat(benchmark.extract(extract)).as(description).isEqualTo(match == null ? null : match.groupSlice(group));

                            RegexpMatcher matcher = pattern.matcher(input);
                            List<Slice> expectedMatches = new ArrayList<>();
                            while (matcher.find()) {
                                expectedMatches.add(matcher.group(group));
                            }
                            assertThat(benchmark.extractAll(extractAll)).as(description).isEqualTo(expectedMatches);

                            // Each compile with generated bytecode defines a class, so one pass over the plans suffices.
                            if (!generateBytecode || call < patterns.length) {
                                RustRegexp compiled = benchmark.compile(compile);
                                assertThat(compiled.capturingGroupCount()).as(description).isEqualTo(pattern.capturingGroupCount());
                                assertThat(compiled.find(input)).as(description).isEqualTo(match != null);
                                assertThat(compiled.pattern().usesScanPlanForDiagnostics()).as(description)
                                        .isEqualTo(contains.patterns[patternIndex].pattern().usesScanPlanForDiagnostics());
                                assertThat(compiled.usesGeneratedBytecode()).as(description).isEqualTo(contains.patterns[patternIndex].usesGeneratedBytecode());
                            }
                        }
                        // A row paired with the wrong plan would time only failure paths.
                        assertThat(planMatched).as(state).containsOnly(true);
                        // Only a pattern with a Unicode Perl class may match differently from RE2. On
                        // the Perl-class workloads, where each capture is one Perl class, every
                        // capture holds a non-ASCII member on some row that matches differently.
                        for (int index = 0; index < patterns.length; index++) {
                            if (workload.startsWith("PERL_")) {
                                assertThat(unicodeDiffered[index]).as("%s pattern %s", state, index).isEqualTo(unicodeClasses[index]);
                                if (unicodeClasses[index]) {
                                    assertThat(nonAsciiCaptureDiffered[index]).as("%s pattern %s", state, index).containsOnly(true);
                                }
                            }
                            else if (unicodeDiffered[index]) {
                                assertThat(unicodeClasses[index]).as("%s pattern %s", state, index).isTrue();
                            }
                        }
                    }
                }
            }
        }
    }

    @Test
    public void testPerlClassesMatchRe2()
    {
        for (String perlClass : List.of("\\d", "\\w")) {
            Re2 re2 = Re2.compile(utf8Slice(perlClass));
            RustRegexp rust = RustRegexp.compile(utf8Slice(BenchmarkRustScanPlan.rustExpression(perlClass, false)));
            // Rust's Unicode \d and \w would also match U+0663, an Arabic-Indic digit, and its
            // Unicode \w would match é.
            List<String> characters = new ArrayList<>(List.of("\u0663", "é"));
            for (char character = 0; character < 0x80; character++) {
                characters.add(String.valueOf(character));
            }
            for (String character : characters) {
                Slice input = utf8Slice(character);
                assertThat(rust.matches(input)).as("%s on U+%04X", perlClass, character.codePointAt(0)).isEqualTo(re2.matches(input));
            }
        }
    }

    private static List<Integer> groupBounds(MatchResult match)
    {
        if (match == null) {
            return null;
        }
        List<Integer> bounds = new ArrayList<>();
        for (int group = 0; group <= match.groupCount(); group++) {
            bounds.add(match.start(group));
            bounds.add(match.end(group));
        }
        return bounds;
    }

    private record Variant(boolean scanPlan, boolean generateBytecode) {}

    private static BenchmarkRustScanPlan.BenchmarkData data(String workload, boolean dotAll, boolean unicodePerlClasses, Variant variant)
    {
        BenchmarkRustScanPlan.BenchmarkData data = new BenchmarkRustScanPlan.BenchmarkData();
        data.workload = workload;
        data.dotAll = dotAll;
        data.unicodePerlClasses = unicodePerlClasses;
        data.scanPlan = variant.scanPlan();
        data.generateBytecode = variant.generateBytecode();
        data.setup();
        return data;
    }

    private static BenchmarkRe2ScanPlan.BenchmarkData re2Data(String workload, boolean dotAll, boolean generateBytecode)
    {
        BenchmarkRe2ScanPlan.BenchmarkData data = new BenchmarkRe2ScanPlan.BenchmarkData();
        data.workload = workload;
        data.dotAll = dotAll;
        data.scanPlan = true;
        data.generateBytecode = generateBytecode;
        data.setup();
        return data;
    }
}
