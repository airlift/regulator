/// Applies each specialized-pattern workload's operation in three variants: the specialized engine,
/// which interprets the scan plan of the default compile; the regular engine, compiled without a
/// scan plan; and compiled, the plan's generated bytecode. The specialized-engine and
/// regular-engine variants make the public [TrinoRegexp] call, and the regular-engine
/// methods take a state that holds only the compile without a scan plan. The compiled variant is
/// const-bound the way an engine like Trino binds a compiled pattern: a per-pattern hidden class
/// invokes the operation's generated handle held as a class-data constant. The handle returns the
/// public method's result and accepts its arguments, except that extract and extract-all bind the
/// group when the handle is created and take only the source when called. Only the
/// `*Generated` methods take the states that compile generated bytecode, so the forks of the
/// other variants load no generated class. The baseline shards run each workload and variant in
/// separate JVMs, so each call site sees one pattern.
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(3)
@Warmup(iterations = 10, time = 1)
@Measurement(iterations = 5, time = 1)
public class BenchmarkSpecializedTrinoRegexp
{
    @State(Scope.Thread)
    public static class ReplaceData
            extends WorkloadData
    {
        @Param("clickbenchHost")
        String workload;

        @Setup
        public void setup()
        {
            load(workload, Operation.REPLACE);
        }

        public void setWorkload(String workload)
        {
            this.workload = workload;
        }
    }

    @State(Scope.Thread)
    public static class ExtractData
            extends WorkloadData
    {
        @Param({"urlHostPort", "quotedField"})
        String workload;

        @Setup
        public void setup()
        {
            load(workload, Operation.EXTRACT);
        }

        public void setWorkload(String workload)
        {
            this.workload = workload;
        }
    }

    @State(Scope.Thread)
    public static class ExtractAllData
            extends WorkloadData
    {
        @Param({"queryParameterNames", "keyValue"})
        String workload;

        @Setup
        public void setup()
        {
            load(workload, Operation.EXTRACT_ALL);
        }

        public void setWorkload(String workload)
        {
            this.workload = workload;
        }
    }

    @State(Scope.Thread)
    public static class RegularEngineReplaceData
            extends RegularEngineData
    {
        @Setup
        public void setup(ReplaceData data)
        {
            load(data);
        }
    }

    @State(Scope.Thread)
    public static class RegularEngineExtractData
            extends RegularEngineData
    {
        @Setup
        public void setup(ExtractData data)
        {
            load(data);
        }
    }

    @State(Scope.Thread)
    public static class RegularEngineExtractAllData
            extends RegularEngineData
    {
        @Setup
        public void setup(ExtractAllData data)
        {
            load(data);
        }
    }

    @State(Scope.Thread)
    public static class GeneratedReplaceData
            extends GeneratedData
    {
        private ReplaceCaller generated;

        @Setup
        public void setup(ReplaceData data)
                throws ReflectiveOperationException
        {
            generated = bind(ReplaceCaller.class, load(data).generatedReplace());
        }
    }

    @State(Scope.Thread)
    public static class GeneratedExtractData
            extends GeneratedData
    {
        private ExtractCaller generated;

        @Setup
        public void setup(ExtractData data)
                throws ReflectiveOperationException
        {
            generated = bind(ExtractCaller.class, load(data).generatedExtract(data.definition.group()));
        }
    }

    @State(Scope.Thread)
    public static class GeneratedExtractAllData
            extends GeneratedData
    {
        private ExtractAllCaller generated;

        @Setup
        public void setup(ExtractAllData data)
                throws ReflectiveOperationException
        {
            generated = bind(ExtractAllCaller.class, load(data).generatedExtractAll(data.definition.group()));
        }
    }

    abstract static class Rotation
    {
        Workload definition;
        private List<Source> sources;
        private int sourceIndex;

        void rotate(Workload definition)
        {
            this.definition = definition;
            sources = definition.sources();
            sourceIndex = 0;
        }

        public void setSourceIndex(int sourceIndex)
        {
            this.sourceIndex = sourceIndex;
        }

        Slice nextSource()
        {
            Slice source = sources.get(sourceIndex).value();
            sourceIndex = (sourceIndex + 1) & (sources.size() - 1);
            return source;
        }
    }

    abstract static class WorkloadData
            extends Rotation
    {
        TrinoRegexp regexp;

        void load(String workloadId, Operation operation)
        {
            Workload workload = TestingSpecializedTrinoRegexpBenchmarkInputs.create(workloadId);
            workload.requireOperation(operation);
            rotate(workload);
            regexp = TrinoRegexp.compile(workload.pattern());
            if (regexp.pattern() == null || !regexp.pattern().usesScanPlanForDiagnostics() || regexp.usesGeneratedBytecode()) {
                throw new IllegalStateException("default compile does not interpret a scan plan: " + workloadId);
            }
        }
    }

    abstract static class RegularEngineData
            extends Rotation
    {
        TrinoRegexp regularEngine;

        void load(WorkloadData data)
        {
            rotate(data.definition);
            regularEngine = TrinoRegexp.compileWithoutScanPlanForTesting(data.definition.pattern());
            if (regularEngine.getClass() != data.regexp.getClass()) {
                throw new IllegalStateException("regular-engine compile of %s is a %s, but its default compile is a %s"
                        .formatted(definition.workloadId(), regularEngine.getClass().getSimpleName(), data.regexp.getClass().getSimpleName()));
            }
            if (regularEngine.pattern().usesScanPlanForDiagnostics()) {
                throw new IllegalStateException("regular-engine compile has a scan plan: " + definition.workloadId());
            }
        }
    }

    abstract static class GeneratedData
            extends Rotation
    {
        TrinoRegexp load(WorkloadData data)
        {
            rotate(data.definition);
            TrinoRegexp regexp = TrinoRegexp.compile(data.definition.pattern(), TrinoRegexp.Options.defaults().setGenerateBytecode(true));
            if (!regexp.usesGeneratedBytecode()) {
                throw new IllegalStateException("pattern has no generated bytecode: " + data.definition.workloadId());
            }
            return regexp;
        }

        <T> T bind(Class<T> type, Optional<MethodHandle> operation)
                throws ReflectiveOperationException
        {
            return constantCaller(type, operation.orElseThrow(() -> new IllegalStateException(
                    "%s has no generated %s handle".formatted(definition.workloadId(), definition.operation().benchmarkName()))));
        }
    }

    interface ReplaceCaller
    {
        Slice replace(Slice source, Slice replacement);
    }

    interface ExtractCaller
    {
        Slice extract(Slice source);
    }

    interface ExtractAllCaller
    {
        List<Slice> extractAll(Slice source);
    }

    @Benchmark
    public Slice replace(ReplaceData data)
    {
        return data.regexp.replace(data.nextSource(), data.definition.replacement());
    }

    @Benchmark
    public Slice replaceRegularEngine(RegularEngineReplaceData data)
    {
        return data.regularEngine.replace(data.nextSource(), data.definition.replacement());
    }

    @Benchmark
    public Slice replaceGenerated(GeneratedReplaceData data)
    {
        return data.generated.replace(data.nextSource(), data.definition.replacement());
    }

    @Benchmark
    public Slice extract(ExtractData data)
    {
        return data.regexp.extract(data.nextSource(), data.definition.group());
    }

    @Benchmark
    public Slice extractRegularEngine(RegularEngineExtractData data)
    {
        return data.regularEngine.extract(data.nextSource(), data.definition.group());
    }

    @Benchmark
    public Slice extractGenerated(GeneratedExtractData data)
    {
        return data.generated.extract(data.nextSource());
    }

    @Benchmark
    public List<Slice> extractAll(ExtractAllData data)
    {
        return data.regexp.extractAll(data.nextSource(), data.definition.group());
    }

    @Benchmark
    public List<Slice> extractAllRegularEngine(RegularEngineExtractAllData data)
    {
        return data.regularEngine.extractAll(data.nextSource(), data.definition.group());
    }

    @Benchmark
    public List<Slice> extractAllGenerated(GeneratedExtractAllData data)
    {
        return data.generated.extractAll(data.nextSource());
    }

    /// Sets up the states of `workloadId` as JMH does and returns its three variants, in
    /// column order, for tests and the Joni verifier.
    public static List<Variant> variantsForTesting(String workloadId)
            throws ReflectiveOperationException
    {
        BenchmarkSpecializedTrinoRegexp benchmark = new BenchmarkSpecializedTrinoRegexp();
        return switch (TestingSpecializedTrinoRegexpBenchmarkInputs.create(workloadId).operation()) {
            case REPLACE -> {
                ReplaceData data = new ReplaceData();
                data.setWorkload(workloadId);
                data.setup();
                RegularEngineReplaceData regularEngine = new RegularEngineReplaceData();
                regularEngine.setup(data);
                GeneratedReplaceData generated = new GeneratedReplaceData();
                generated.setup(data);
                yield List.of(
                        new Variant("specialized engine", data, () -> benchmark.replace(data)),
                        new Variant("regular engine", regularEngine, () -> benchmark.replaceRegularEngine(regularEngine)),
                        new Variant("compiled", generated, () -> benchmark.replaceGenerated(generated)));
            }
            case EXTRACT -> {
                ExtractData data = new ExtractData();
                data.setWorkload(workloadId);
                data.setup();
                RegularEngineExtractData regularEngine = new RegularEngineExtractData();
                regularEngine.setup(data);
                GeneratedExtractData generated = new GeneratedExtractData();
                generated.setup(data);
                yield List.of(
                        new Variant("specialized engine", data, () -> benchmark.extract(data)),
                        new Variant("regular engine", regularEngine, () -> benchmark.extractRegularEngine(regularEngine)),
                        new Variant("compiled", generated, () -> benchmark.extractGenerated(generated)));
            }
            case EXTRACT_ALL -> {
                ExtractAllData data = new ExtractAllData();
                data.setWorkload(workloadId);
                data.setup();
                RegularEngineExtractAllData regularEngine = new RegularEngineExtractAllData();
                regularEngine.setup(data);
                GeneratedExtractAllData generated = new GeneratedExtractAllData();
                generated.setup(data);
                yield List.of(
                        new Variant("specialized engine", data, () -> benchmark.extractAll(data)),
                        new Variant("regular engine", regularEngine, () -> benchmark.extractAllRegularEngine(regularEngine)),
                        new Variant("compiled", generated, () -> benchmark.extractAllGenerated(generated)));
            }
        };
    }

    /// One variant of a workload: its benchmark method and the state whose rotation that method
    /// advances.
    public static final class Variant
    {
        private final String name;
        private final Rotation state;
        private final Supplier<Object> benchmark;

        private Variant(String name, Rotation state, Supplier<Object> benchmark)
        {
            this.name = name;
            this.state = state;
            this.benchmark = benchmark;
        }

        public String name()
        {
            return name;
        }

        public void setSourceIndex(int sourceIndex)
        {
            state.setSourceIndex(sourceIndex);
        }

        /// Calls the benchmark method once, on the next source of the rotation.
        public Object invoke()
        {
            return benchmark.get();
        }

        /// Calls the benchmark method on the source at `sourceIndex`.
        public Object invoke(int sourceIndex)
        {
            setSourceIndex(sourceIndex);
            return invoke();
        }
    }

    /// Returns an instance of a per-pattern hidden class implementing `type`, whose one
    /// method invokes `operation` held as a class-data constant, as
    /// `BenchmarkTrinoLikeTpch` binds a constant pattern. `operation` must have that
    /// method's type, which takes and returns only references.
    private static <T> T constantCaller(Class<T> type, MethodHandle operation)
            throws ReflectiveOperationException
    {
        Method[] methods = type.getDeclaredMethods();
        if (methods.length != 1) {
            throw new IllegalArgumentException("caller interface does not have one method: " + type.getName());
        }
        Method method = methods[0];
        MethodType methodType = MethodType.methodType(method.getReturnType(), method.getParameterTypes());
        if (methodType.hasPrimitives()) {
            throw new IllegalArgumentException("caller interface method has a primitive or void parameter or return: " + type.getName());
        }
        if (!operation.type().equals(methodType)) {
            throw new IllegalArgumentException("operation " + operation.type() + " does not implement " + type.getName());
        }
        ClassDesc owner = ClassDesc.of(BenchmarkSpecializedTrinoRegexp.class.getPackageName() + ".ConstantSpecializedCaller");
        DirectMethodHandleDesc bootstrap = MethodHandleDesc.ofMethod(
                DirectMethodHandleDesc.Kind.STATIC,
                CD_MethodHandles,
                "classDataAt",
                MethodTypeDesc.of(CD_Object, CD_MethodHandles_Lookup, CD_String, CD_Class, CD_int));
        DynamicConstantDesc<?> boundOperation = DynamicConstantDesc.ofNamed(bootstrap, "_", CD_MethodHandle, 0);
        MethodTypeDesc descriptor = methodType.describeConstable().orElseThrow();
        byte[] bytecode = ClassFile.of().build(owner, builder -> {
            builder.withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_FINAL);
            builder.withInterfaceSymbols(type.describeConstable().orElseThrow());
            builder.withMethodBody(INIT_NAME, MethodTypeDesc.of(CD_void), ClassFile.ACC_PUBLIC, code ->
                    code.aload(0).invokespecial(CD_Object, INIT_NAME, MethodTypeDesc.of(CD_void)).return_());
            builder.withMethodBody(method.getName(), descriptor, ClassFile.ACC_PUBLIC, code -> {
                code.loadConstant(boundOperation);
                for (int parameter = 0; parameter < descriptor.parameterCount(); parameter++) {
                    code.aload(parameter + 1);
                }
                code.invokevirtual(CD_MethodHandle, "invokeExact", descriptor).areturn();
            });
        });
        MethodHandles.Lookup lookup = MethodHandles.lookup().defineHiddenClassWithClassData(bytecode, List.of(operation), true, MethodHandles.Lookup.ClassOption.NESTMATE);
        return type.cast(lookup.lookupClass().getConstructor().newInstance());
    }

    public static void main(String[] args)
            throws Exception
    {
        Options options = buildOptions(BenchmarkSpecializedTrinoRegexp.class, args);
        new Runner(options).run();
    }
}
